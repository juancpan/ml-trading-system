# --- Weight Export Function ---


def extract_and_export_weights(optimization_results, label, asset_names):
    """
    Extract portfolio weights for a given label and write them to a JSON file.

    The output file is written to algos/backtest_code/data/<label>_weights.json,
    matching the format of hrp_weights.json (flat {ticker: weight} dict), but
    sorted by weight in descending order.

    Supported labels:
        - 'max_sharpe'  : Maximum Sharpe Ratio optimized portfolio
        - 'min_vol'     : Minimum Volatility optimized portfolio
        - 'target_vol'  : Target Volatility optimized portfolio (best)
        - 'mc_N'        : N-th Monte Carlo portfolio near target volatility
                          (1-indexed, e.g. 'mc_1', 'mc_2', 'mc_3')

    Parameters:
    -----------
    optimization_results : dict
        The results dictionary returned by perform_portfolio_optimization().
    label : str
        Portfolio label to export.
    asset_names : list
        Ordered list of ticker symbols matching the Weights arrays.

    Returns:
    --------
    str
        Path to the written JSON file.

    Raises:
    -------
    ValueError
        If the label is not recognised or the corresponding portfolio is
        not present in the results.
    """
    import re as _re

    weights_array = None

    is_miqp = optimization_results.get("mode") == "miqp"

    if label == "max_sharpe":
        if "max_sharpe_optimized" not in optimization_results:
            raise ValueError("max_sharpe portfolio not found in optimization results.")
        entry = optimization_results["max_sharpe_optimized"]
        if is_miqp:
            # MIQP stores integer shares; derive weights from shares * prices
            shares = np.array(entry["Shares"])
            prices_usd = np.array(optimization_results["prices_usd"])
            values = shares * prices_usd
            total_val = values.sum()
            weights_array = (
                (values / total_val).tolist() if total_val > 0 else [0.0] * len(shares)
            )
        else:
            weights_array = entry.get("Weights")

    elif label == "min_vol":
        if "min_volatility_optimized" not in optimization_results:
            raise ValueError("min_vol portfolio not found in optimization results.")
        entry = optimization_results["min_volatility_optimized"]
        weights_array = entry.get("Weights")

    elif label == "target_vol":
        tv = optimization_results.get("target_volatility_optimized")
        if not tv or "Optimized Best" not in tv:
            raise ValueError(
                "target_vol portfolio not found in optimization results. "
                "Did you pass --target_volatility?"
            )
        weights_array = tv["Optimized Best"].get("Weights")

    elif _re.match(r"^mc_\d+$", label):
        idx = int(label.split("_")[1]) - 1  # 1-indexed -> 0-indexed
        tv = optimization_results.get("target_volatility_optimized")
        if not tv:
            raise ValueError(
                f"No target_volatility_optimized in results for label '{label}'. "
                "Did you pass --target_volatility?"
            )
        mc_list = tv.get("Monte Carlo Near Target", [])
        if idx < 0 or idx >= len(mc_list):
            raise ValueError(
                f"Monte Carlo portfolio '{label}' not found. "
                f"Only {len(mc_list)} MC portfolio(s) available (mc_1 .. mc_{len(mc_list)})."
            )
        weights_array = mc_list[idx].get("Weights")

    else:
        raise ValueError(
            f"Unrecognised portfolio label: '{label}'. "
            "Supported labels: 'max_sharpe', 'min_vol', 'target_vol', 'mc_1', 'mc_2', ..."
        )

    if weights_array is None:
        raise ValueError(f"Weights not found for portfolio label '{label}'.")

    # Build {ticker: weight} dict
    weights_dict = {}
    for ticker, weight in zip(asset_names, weights_array):
        if isinstance(weight, (np.floating, np.integer)):
            weight = float(weight)
        weights_dict[ticker] = weight

    # Sort by weight descending
    sorted_weights = dict(
        sorted(weights_dict.items(), key=lambda item: item[1], reverse=True)
    )

    # Write to algos/backtest_code/data/<label>_weights.json
    output_dir = os.path.join(BASE_SCRIPT_DIR, "data")
    os.makedirs(output_dir, exist_ok=True)
    output_path = os.path.join(output_dir, f"{label}_weights.json")

    with open(output_path, "w") as f:
        json.dump(sorted_weights, f, indent=2)

    logging.info(f"\nExported '{label}' portfolio weights to: {output_path}")
    logging.info(f"  {len(sorted_weights)} tickers, sorted by weight (descending)")

    return output_path


# --- Main Workflow Execution ---


def main_workflow(args):
    """
    Main function to run the complete financial analysis workflow.
    Accepts arguments for start_date, end_date, interval, and target_volatility.
    """
    # Resolve seed (support both CLI and programmatic callers)
    seed = getattr(args, "seed", 42)
    logging.info("Starting financial analysis workflow...")
    logging.info(f"Random seed: {seed}")

    # Calculate periods per year based on interval
    periods_per_year = get_periods_per_year(args.interval)
    logging.info(
        f"Using {periods_per_year} periods per year for interval '{args.interval}'"
    )

    # Construct DATA_FILE_PATH using parsed arguments for dynamic filename
    DATA_FILE_PATH = os.path.join(
        BASE_DATA_DIR,
        f"financial_data_combined_prices_{args.start}_{args.end}_{args.interval}.csv",
    )
    logging.info(f"Attempting to load data from: {DATA_FILE_PATH}")

    # Step 1: Load and Preprocess Data
    log_returns = load_and_preprocess_data(
        DATA_FILE_PATH, args.start, args.end, seed=seed
    )
    if log_returns.empty:
        logging.error("Workflow terminated due to data loading/preprocessing failure.")
        return

    # Step 1b: Extract latest prices for MIQP mode
    prices_dict = None
    if args.mode == "miqp":
        logging.info(f"\nMIQP mode: Extracting latest prices from {DATA_FILE_PATH}")
        prices_dict = get_latest_prices_from_csv(
            DATA_FILE_PATH, log_returns.columns.tolist()
        )
        logging.info(f"Extracted prices for {len(prices_dict)} assets")

    # Step 2: Perform Normality Tests
    perform_normality_tests(log_returns, output_dir=BASE_IMAGE_DIR, timestamp=TIMESTAMP)

    # Parse fixed weights if provided
    fixed_weights_dict = None
    if args.fixed_weights:
        fixed_weights_dict = {}
        for weight_spec in args.fixed_weights:
            try:
                asset, weight = weight_spec.split("=")
                fixed_weights_dict[asset] = float(weight)
            except ValueError:
                logging.error(
                    f"Invalid fixed weight specification: {weight_spec}. Expected format: ASSET=WEIGHT"
                )
                return
        logging.info(f"Fixed weights specified: {fixed_weights_dict}")

    # Parse Kelly leverages if provided
    kelly_leverages_dict = {}
    if args.kelly_leverages:
        for leverage_spec in args.kelly_leverages:
            try:
                asset, leverage = leverage_spec.split("=")
                kelly_leverages_dict[asset] = float(leverage)
            except ValueError:
                logging.error(
                    f"Invalid Kelly leverage specification: {leverage_spec}. Expected format: ASSET=LEVERAGE"
                )
                return
        logging.info(f"Kelly leverages specified: {kelly_leverages_dict}")
    else:
        # Default all leverages to 1.0 (no leverage)
        for asset in log_returns.columns:
            kelly_leverages_dict[asset] = 1.0
        logging.info(
            "No Kelly leverages specified. Using default leverage of 1.0 for all assets."
        )

    # Parse lot sizes if provided (MIQP mode)
    lot_sizes_dict = {}
    if args.lot_sizes:
        for lot_spec in args.lot_sizes:
            try:
                ticker, size = lot_spec.split("=")
                lot_sizes_dict[ticker] = int(size)
            except ValueError:
                logging.error(
                    f"Invalid lot size specification: {lot_spec}. Expected format: TICKER=SIZE"
                )
                return
        logging.info(f"Lot sizes specified: {lot_sizes_dict}")

    # Parse exchange rates if provided (MIQP mode)
    exchange_rates_dict = {"USD": 1.0}  # Always include USD as base
    if args.exchange_rates:
        for rate_spec in args.exchange_rates:
            try:
                currency, rate = rate_spec.split("=")
                exchange_rates_dict[currency] = float(rate)
            except ValueError:
                logging.error(
                    f"Invalid exchange rate specification: {rate_spec}. Expected format: CURRENCY=RATE"
                )
                return
        logging.info(f"Exchange rates specified: {exchange_rates_dict}")

    # Parse reference portfolios from portfolio exploration log (if provided)
    reference_portfolios = None
    if args.portfolio_log:
        logging.info(f"\n--- Parsing Reference Portfolios from Log ---")
        logging.info(f"  Log file: {args.portfolio_log}")
        reference_portfolios = parse_portfolio_exploration_log(args.portfolio_log)
        if reference_portfolios:
            logging.info(f"  Found {len(reference_portfolios)} reference portfolio(s)")
        else:
            logging.warning(f"  No portfolios parsed from log file")

    # Step 3: Perform Portfolio Optimization
    optimization_results = perform_portfolio_optimization(
        log_returns,
        num_portfolios=500000,
        risk_free_rate=args.risk_free_rate,
        output_dir=BASE_IMAGE_DIR,
        timestamp=TIMESTAMP,
        target_volatility=args.target_volatility,
        min_asset_weight=args.min_asset_weight,
        fixed_weights=fixed_weights_dict,
        # MIQP parameters
        optimization_mode=args.mode,
        portfolio_budget=args.budget,
        lot_sizes=lot_sizes_dict if lot_sizes_dict else None,
        exchange_rates=exchange_rates_dict if len(exchange_rates_dict) > 1 else None,
        prices_dict=prices_dict,  # Pass extracted prices
        miqp_solver=args.miqp_solver,
        frontier_points=args.frontier_points,
        # Reference portfolios
        reference_portfolios=reference_portfolios,
        # Interval-aware annualization
        periods_per_year=periods_per_year,
        # Reproducibility
        seed=seed,
    )

    # Step 3b: Export weights if --export_weights was provided
    if (
        args.export_weights
        and optimization_results
        and "asset_names" in optimization_results
    ):
        try:
            export_path = extract_and_export_weights(
                optimization_results,
                args.export_weights,
                optimization_results["asset_names"],
            )
            logging.info(f"Weights exported successfully to: {export_path}")
        except ValueError as e:
            logging.error(f"Failed to export weights: {e}")

    # Step 4: Calculate Leveraged Portfolios (CONTINUOUS MODE ONLY)
    # MIQP mode already provides exact shares, skip leverage calculation
    if (
        optimization_results
        and "asset_names" in optimization_results
        and optimization_results.get("mode") != "miqp"
    ):
        logging.info("\n" + "=" * 50)
        logging.info("LEVERAGED PORTFOLIO ANALYSIS")
        logging.info("=" * 50)

        asset_names = optimization_results["asset_names"]

        # Process Max Sharpe Portfolio
        if "max_sharpe_optimized" in optimization_results:
            max_sharpe_data = optimization_results["max_sharpe_optimized"]
