def get_periods_per_year(interval: str = "1d") -> int:
    """Get annualization factor based on data interval."""
    interval_map = {
        "1d": 252,  # Daily trading days
        "1wk": 52,  # Weekly
        "1mo": 12,  # Monthly
        "1h": 252 * 7,  # Hourly (approximate)
    }
    return interval_map.get(interval, 252)


