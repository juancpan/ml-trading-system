def get_latest_prices_from_csv(csv_path, tickers):
    """
    Extract latest prices from CSV file for MIQP optimization.

    MIQP needs actual prices (not just returns) to calculate position sizes.

    Parameters:
    -----------
    csv_path : str
        Path to price CSV file
    tickers : list
        List of ticker symbols

    Returns:
    --------
    dict: {ticker: latest_price}
    """
    try:
        if str(csv_path).endswith(".parquet"):
            df = pd.read_parquet(csv_path)
            if df.index.name != "Date":
                df.index.name = "Date"
        else:
            df = pd.read_csv(csv_path, index_col="Date", parse_dates=True)

        # Get latest price for each ticker using robust estimation.
        # yfinance can return corrupted data during stock split transitions
        # (mixing pre-split and post-split prices for days around the split).
        #
        # Strategy: take the last 5 trading days. Cluster them by price level
        # (within 2x of each other = same cluster). Pick the cluster that
        # contains the most recent day. This handles:
        # - Real splits: post-split prices cluster together at the new level
        # - Garbage spikes: isolated outlier days get outvoted
        # - Normal stocks: all 5 days cluster together, latest is returned
        prices_dict = {}
        for ticker in tickers:
            if ticker in df.columns:
                prices = df[ticker].dropna()
                if len(prices) >= 5:
                    tail = prices.iloc[-5:]
                    latest = tail.iloc[-1]
                    # Find which prices are "close" to the latest
                    # (within 2x ratio = same price regime)
                    ratio = tail / latest
                    same_regime = tail[(ratio > 0.5) & (ratio < 2.0)]
                    if len(same_regime) >= 2:
                        # Majority agrees with the latest price level
                        prices_dict[ticker] = latest
                    else:
                        # Latest is an outlier -- use the majority cluster
                        # Try the second-to-last as pivot instead
                        second = tail.iloc[-2]
                        ratio2 = tail / second
                        same_regime2 = tail[(ratio2 > 0.5) & (ratio2 < 2.0)]
                        if len(same_regime2) >= 2:
                            prices_dict[ticker] = same_regime2.iloc[-1]
                        else:
                            # No clear majority -- use median as safe fallback
                            prices_dict[ticker] = tail.median()
                elif len(prices) > 0:
                    prices_dict[ticker] = prices.iloc[-1]
                else:
                    logging.warning(
                        f"No valid prices for {ticker}, using 100.0 as fallback"
                    )
                    prices_dict[ticker] = 100.0
            else:
                logging.warning(
                    f"Ticker {ticker} not found in CSV, using 100.0 as fallback"
                )
                prices_dict[ticker] = 100.0

        return prices_dict

    except Exception as e:
        logging.error(f"Failed to load prices from CSV: {e}")
        # Fallback to dummy prices
        return {ticker: 100.0 for ticker in tickers}


