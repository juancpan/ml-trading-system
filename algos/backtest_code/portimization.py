def are_weights_distinct(
    weights1, weights2, threshold=0.05
):  # Threshold for distinguishing portfolios
    """
    Checks if two weight arrays are distinct enough based on Euclidean distance.
    """
    return np.linalg.norm(weights1 - weights2) > threshold


def expand_weights(free_weights, fixed_indices, fixed_values, num_assets):
    """
    Expands free weights to full portfolio weights by inserting fixed weights.
    """
    full_weights = np.zeros(num_assets)
    free_idx = 0

    for i in range(num_assets):
        if i in fixed_indices:
            # Use fixed weight for this asset
            idx_in_fixed = fixed_indices.index(i)
            full_weights[i] = fixed_values[idx_in_fixed]
        else:
            # Use optimized weight for this asset
            full_weights[i] = free_weights[free_idx]
            free_idx += 1

    return full_weights


def calculate_leveraged_portfolio(
    unleveraged_weights,
    kelly_leverages,
    max_total_leverage=2.0,
    fractional_kelly=0.4,
    preserve_structure=True,
):
    """
    Calculates leveraged portfolio weights from unleveraged weights and Kelly fractions.

    Parameters:
    -----------
    unleveraged_weights : dict or np.array
        Base portfolio weights (should sum to 1)
    kelly_leverages : dict
        Kelly fractions/leverages for each asset
    max_total_leverage : float
        Maximum total portfolio leverage allowed
    fractional_kelly : float
        Fraction of full Kelly to use (default 0.4 for conservative approach)
    preserve_structure : bool
        If True, preserves relative portfolio structure when scaling down leverage

    Returns:
    --------
    dict
        Contains both leveraged and unleveraged portfolio information
    """
    # Convert to consistent format
    if isinstance(unleveraged_weights, np.ndarray):
        weights_dict = {i: w for i, w in enumerate(unleveraged_weights)}
    else:
        weights_dict = unleveraged_weights

    # Apply fractional Kelly
    adjusted_kellys = {}
    for asset, kelly in kelly_leverages.items():
        adjusted_kellys[asset] = min(kelly * fractional_kelly, max_total_leverage)

    # Calculate raw leveraged positions
    raw_leveraged = {}
    for asset, weight in weights_dict.items():
        kelly = adjusted_kellys.get(asset, 1.0)  # Default to 1 if no Kelly provided
        raw_leveraged[asset] = weight * kelly

    # Calculate total leverage
    total_leverage = sum(raw_leveraged.values())

    # Scale down if exceeds max leverage
    final_leveraged = {}
    scaling_factor = 1.0

    if total_leverage > max_total_leverage:
        if preserve_structure:
            # Scale all positions proportionally
            scaling_factor = max_total_leverage / total_leverage
            final_leveraged = {k: v * scaling_factor for k, v in raw_leveraged.items()}
        else:
            # Cap individual positions while maintaining ratios where possible
            remaining_leverage = max_total_leverage
            sorted_positions = sorted(
                raw_leveraged.items(), key=lambda x: x[1], reverse=True
            )

            for asset, position in sorted_positions:
                if position <= remaining_leverage:
                    final_leveraged[asset] = position
                    remaining_leverage -= position
                else:
                    final_leveraged[asset] = remaining_leverage
                    remaining_leverage = 0
    else:
        final_leveraged = raw_leveraged

    # Calculate effective leverage for each asset
    effective_leverages = {}
    for asset, weight in weights_dict.items():
        if weight > 0:
            effective_leverages[asset] = final_leveraged[asset] / weight
        else:
            effective_leverages[asset] = 0

    return {
        "unleveraged_weights": weights_dict,
        "kelly_leverages": kelly_leverages,
        "adjusted_kellys": adjusted_kellys,
        "raw_leveraged_positions": raw_leveraged,
        "final_leveraged_positions": final_leveraged,
        "total_leverage": sum(final_leveraged.values()),
        "scaling_factor": scaling_factor,
        "effective_leverages": effective_leverages,
    }


def contract_weights(full_weights, free_indices):
    """
    Extracts only the free weights from full portfolio weights.
    """
    return full_weights[free_indices]


