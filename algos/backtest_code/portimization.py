def calculate_sortino_ratio(returns, risk_free_rate=0.01, periods_per_year=252):
    """
    Calculate Sortino Ratio (uses downside deviation instead of total volatility).

    Sortino = (Annual Return - Rf) / Downside Deviation
    Only penalizes negative returns, not upside volatility.
    """
    excess_returns = returns - risk_free_rate / periods_per_year
    downside_returns = excess_returns[excess_returns < 0]

    if len(downside_returns) == 0:
        return np.inf  # No downside, perfect Sortino

    downside_deviation = np.sqrt((downside_returns**2).mean()) * np.sqrt(
        periods_per_year
    )
    annual_return = returns.mean() * periods_per_year

    if downside_deviation == 0:
        return np.inf

    return (annual_return - risk_free_rate) / downside_deviation


def calculate_calmar_ratio(returns, max_drawdown, periods_per_year=252):
    """
    Calculate Calmar Ratio (annual return / max drawdown).

    Measures return per unit of drawdown risk.
    """
    annual_return = returns.mean() * periods_per_year

    if max_drawdown == 0:
        return np.inf if annual_return > 0 else 0

    return annual_return / abs(max_drawdown)


def calculate_omega_ratio(returns, threshold=0.0):
    """
    Calculate Omega Ratio (probability-weighted ratio of gains to losses).

    Omega = Sum(returns > threshold) / Sum(returns < threshold)

    Unlike Sharpe, considers the entire return distribution.
    """
    gains = returns[returns > threshold] - threshold
    losses = threshold - returns[returns < threshold]

    sum_losses = losses.sum()

    if sum_losses == 0:
        return np.inf if gains.sum() > 0 else 1.0

    return gains.sum() / sum_losses


def calculate_var(returns, confidence=0.95):
    """
    Calculate Value at Risk at given confidence level.

    VaR = percentile of daily returns (negative value indicates loss)
    """
    return np.percentile(returns, (1 - confidence) * 100)


def calculate_cvar(returns, confidence=0.95):
    """
    Calculate Conditional VaR (Expected Shortfall).

    CVaR = average of returns below VaR (expected loss in worst cases)
    """
    var = calculate_var(returns, confidence)
    tail_returns = returns[returns <= var]
    if len(tail_returns) == 0:
        return var
    return tail_returns.mean()


def calculate_psr(
    sharpe_observed, n_returns, sharpe_benchmark=0.0, skewness=0.0, kurtosis=3.0
):
    """
    Calculate Probabilistic Sharpe Ratio (Bailey & López de Prado).

    PSR = probability that true Sharpe > benchmark, given observed data.

    Accounts for:
    - Sample size (more data = higher confidence)
    - Non-normality (skewness, kurtosis)

    Reference: Bailey & López de Prado (2012)
    """
    if n_returns < 2:
        return 0.5  # Insufficient data

    # Standard error of Sharpe ratio (accounting for non-normality)
    se_sharpe = np.sqrt(
        (
            1
            + 0.5 * sharpe_observed**2
            - skewness * sharpe_observed
            + (kurtosis - 3) / 4 * sharpe_observed**2
        )
        / (n_returns - 1)
    )

    if se_sharpe == 0:
        return 1.0 if sharpe_observed > sharpe_benchmark else 0.0

    # Z-score
    z = (sharpe_observed - sharpe_benchmark) / se_sharpe

    # Probability (using normal CDF)
    return scs.norm.cdf(z)


def calculate_max_drawdown(returns):
    """
    Calculate maximum drawdown from a return series.

    Returns:
    --------
    tuple: (max_drawdown, drawdown_start_date, drawdown_end_date, recovery_date)
    """
    cumulative = (1 + returns).cumprod()
    running_max = cumulative.cummax()
    drawdown = (cumulative - running_max) / running_max

    max_dd = drawdown.min()
    max_dd_end_idx = (
        drawdown.idxmin() if hasattr(drawdown, "idxmin") else drawdown.argmin()
    )

    # Find start of drawdown (peak before trough)
    if hasattr(returns, "index"):
        peak_idx = cumulative[:max_dd_end_idx].idxmax()
    else:
        peak_idx = cumulative[:max_dd_end_idx].argmax()

    return abs(max_dd), peak_idx, max_dd_end_idx


def calculate_comprehensive_portfolio_metrics(
    weights, returns_df, risk_free_rate=0.01, periods_per_year=252
):
    """
    Calculate comprehensive portfolio metrics from weights and returns data.

    Parameters:
    -----------
    weights : np.array or dict
        Portfolio weights (should align with returns_df columns)
    returns_df : pd.DataFrame
        Daily log returns for all assets
    risk_free_rate : float
        Annual risk-free rate (default: 0.01 = 1%)
    periods_per_year : int
        Trading periods per year (default: 252)

    Returns:
    --------
    dict with comprehensive metrics:
        - Basic: annual_return, annual_volatility, sharpe_ratio
        - Risk-adjusted: sortino_ratio, calmar_ratio, omega_ratio
        - Tail risk: var_95, cvar_95
        - Statistical: psr, skewness, kurtosis
        - Drawdown: max_drawdown
        - Concentration: top3_concentration, herfindahl_index
    """
    # Convert weights to array if dict
    if isinstance(weights, dict):
        weights_array = np.array([weights.get(col, 0) for col in returns_df.columns])
    else:
        weights_array = np.array(weights)

    # Calculate portfolio returns
    portfolio_returns = (returns_df * weights_array).sum(axis=1)

    # Basic metrics
    annual_return = portfolio_returns.mean() * periods_per_year
    annual_volatility = portfolio_returns.std() * np.sqrt(periods_per_year)
    sharpe_ratio = (
        (annual_return - risk_free_rate) / annual_volatility
        if annual_volatility > 0
        else 0
    )

    # Max drawdown
    max_dd, dd_start, dd_end = calculate_max_drawdown(portfolio_returns)

    # Risk-adjusted metrics
    sortino = calculate_sortino_ratio(
        portfolio_returns, risk_free_rate, periods_per_year
    )
    calmar = calculate_calmar_ratio(portfolio_returns, max_dd, periods_per_year)
    omega = calculate_omega_ratio(portfolio_returns, threshold=0.0)

    # Tail risk metrics
    var_95 = calculate_var(portfolio_returns, confidence=0.95)
    cvar_95 = calculate_cvar(portfolio_returns, confidence=0.95)

    # Statistical metrics
    skewness = scs.skew(portfolio_returns)
    kurtosis = scs.kurtosis(portfolio_returns) + 3  # Convert to excess kurtosis + 3

    # PSR
    psr = calculate_psr(sharpe_ratio, len(portfolio_returns), 0.0, skewness, kurtosis)

    # Concentration metrics
    sorted_weights = sorted(weights_array, reverse=True)
    top3_concentration = (
        sum(sorted_weights[:3]) if len(sorted_weights) >= 3 else sum(sorted_weights)
    )
    herfindahl_index = sum(w**2 for w in weights_array)

    # Number of positions
