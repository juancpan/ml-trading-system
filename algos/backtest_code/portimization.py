def load_lse_currency_overrides() -> dict:
    """Load per-ticker LSE currency overrides for non-GBX listings."""
    if not LSE_CURRENCY_OVERRIDES_PATH.exists():
        logging.info(
            f"LSE currency override file not found: {LSE_CURRENCY_OVERRIDES_PATH}"
        )
        return {}

    try:
        with LSE_CURRENCY_OVERRIDES_PATH.open("r", encoding="utf-8") as f:
            payload = json.load(f)
    except Exception as e:
        logging.warning(
            f"Failed to load LSE currency overrides from {LSE_CURRENCY_OVERRIDES_PATH}: {e}"
        )
        return {}

    overrides = {}
    for ticker, currency in payload.items():
        if (
            isinstance(ticker, str)
            and isinstance(currency, str)
            and not ticker.startswith("_")
        ):
            normalized_ticker = ticker.upper().strip()
            if normalized_ticker.endswith(".L"):
                overrides[normalized_ticker] = currency.upper().strip()

    logging.info(
        f"Loaded {len(overrides)} LSE currency overrides from {LSE_CURRENCY_OVERRIDES_PATH}"
    )
    return overrides


def resolve_ticker_currency(
    ticker: str,
    exchange_mgr,
    lse_currency_overrides: dict,
) -> str:
    """Resolve ticker currency using hints + LSE overrides + exchange mapping."""
    if ticker in CURRENCY_HINTS:
        return CURRENCY_HINTS[ticker]

    normalized_ticker = ticker.upper().strip()
    if normalized_ticker.endswith(".L") and normalized_ticker in lse_currency_overrides:
        return lse_currency_overrides[normalized_ticker]

    return exchange_mgr.get_currency(ticker)


def normalize_to_usd(prices_dict, tickers, exchange_rates):
    """
    Convert all asset prices to USD using exchange rates.

    This is critical for multi-currency portfolios - all optimization
    is performed in USD terms.

    Parameters:
    -----------
    prices_dict : dict
        {ticker: price_in_native_currency}
        Example: {'NVDA': 137.45, '8002.T': 3758}
    tickers : list
        Ordered list of ticker symbols
    exchange_rates : dict
        {currency: rate_to_usd}
        Example: {'USD': 1.0, 'JPY': 0.0067, 'GBP': 1.27}

    Returns:
    --------
    np.array
        Prices in USD (same order as tickers)

    Example:
    --------
    >>> prices = {'NVDA': 137.45, '8002.T': 3758}
    >>> rates = {'USD': 1.0, 'JPY': 0.0067}
    >>> prices_usd = normalize_to_usd(prices, ['NVDA', '8002.T'], rates)
    >>> # Returns: [137.45, 25.18]  (3758 JPY × 0.0067 = 25.18 USD)
    """
    # Import ExchangeManager locally to avoid circular dependency
    import sys
    import os

    sys.path.insert(
        0, os.path.join(os.path.dirname(__file__), "..", "..", "execution")
    )
    from exchange_manager import ExchangeManager

    exchange_mgr = ExchangeManager()
    lse_currency_overrides = load_lse_currency_overrides()
    prices_usd = []

    for ticker in tickers:
        if ticker not in prices_dict:
            raise ValueError(f"Ticker {ticker} not found in prices_dict")

        price_native = prices_dict[ticker]

        currency = resolve_ticker_currency(ticker, exchange_mgr, lse_currency_overrides)

        if currency not in exchange_rates:
            raise ValueError(
                f"Missing exchange rate for {currency} (needed for ticker: {ticker}). "
                f"Provided rates: {list(exchange_rates.keys())}"
            )

        price_usd = price_native * exchange_rates[currency]
        prices_usd.append(price_usd)

        # Log currency conversions (show for all non-USD)
        if currency != "USD":
            logging.info(
                f"  {ticker}: {price_native:.2f} {currency} × {exchange_rates[currency]:.5f} = ${price_usd:.2f} USD"
            )

    return np.array(prices_usd)


def validate_miqp_inputs(
    tickers, prices_dict, portfolio_budget, lot_sizes, exchange_rates
):
    """
    Validate MIQP inputs before optimization.

    Critical checks to prevent infeasible problems or poor results.

    Parameters:
    -----------
    tickers : list
        Asset symbols
    prices_dict : dict
        {ticker: price_native_currency}
    portfolio_budget : float
        Total portfolio value in USD
    lot_sizes : dict
        {ticker: lot_size}
    exchange_rates : dict
        {currency: rate_to_usd}

    Raises:
    -------
    ValueError if critical validation fails

    Returns:
    --------
    True if all checks pass (with warnings logged)
    """
    import sys
    import os

    sys.path.insert(
        0, os.path.join(os.path.dirname(__file__), "..", "..", "execution")
    )
    from exchange_manager import ExchangeManager

    exchange_mgr = ExchangeManager()
    lse_currency_overrides = load_lse_currency_overrides()

    errors = []
    warnings = []

    logging.info("\n--- MIQP Input Validation ---")

    # 1. Check exchange rates for all currencies (use hints!)
    required_currencies = set()
    for t in tickers:
        required_currencies.add(
            resolve_ticker_currency(t, exchange_mgr, lse_currency_overrides)
        )

    missing_currencies = required_currencies - set(exchange_rates.keys())

    if missing_currencies:
        errors.append(
            f"Missing exchange rates for: {missing_currencies}. "
            f"Required for tickers: {[t for t in tickers if resolve_ticker_currency(t, exchange_mgr, lse_currency_overrides) in missing_currencies]}"
        )

    logging.info(f"  Currencies required: {required_currencies}")
    logging.info(f"  Exchange rates provided: {set(exchange_rates.keys())}")

    # 2. Minimum budget check
    MIN_BUDGET_INTL = 10000  # $10k minimum for international portfolios
    has_international = "USD" not in required_currencies or len(required_currencies) > 1

    if has_international and portfolio_budget < MIN_BUDGET_INTL:
        warnings.append(
            f"Portfolio budget ${portfolio_budget:,.0f} is below recommended "
            f"${MIN_BUDGET_INTL:,.0f} for international stocks with lot sizes. "
            f"May result in highly concentrated portfolio (2-3 positions only)."
        )

    # 3. Lot size feasibility check
    for ticker in tickers:
        lot_size = lot_sizes.get(ticker, exchange_mgr.get_lot_size(ticker))
        price_native = prices_dict[ticker]

        currency = resolve_ticker_currency(ticker, exchange_mgr, lse_currency_overrides)

        price_usd = price_native * exchange_rates.get(currency, 1.0)

        min_position_usd = lot_size * price_usd

        if min_position_usd > portfolio_budget * 0.5:
            errors.append(
                f"{ticker}: Minimum lot position (${min_position_usd:,.0f}) "
                f"exceeds 50% of budget (${portfolio_budget:,.0f}). "
                f"Lot size {lot_size} too restrictive for this budget."
            )

        if min_position_usd > portfolio_budget * 0.2:
            warnings.append(
                f"{ticker}: Minimum lot position (${min_position_usd:,.0f}) "
                f"is {min_position_usd / portfolio_budget:.1%} of budget. "
                f"May limit diversification."
            )

    # 4. Estimate maximum positions achievable
    prices_usd = normalize_to_usd(prices_dict, tickers, exchange_rates)
    lot_sizes_arr = np.array(
        [lot_sizes.get(t, exchange_mgr.get_lot_size(t)) for t in tickers]
    )

    min_position_values = prices_usd * lot_sizes_arr
    # Conservative estimate: assume equal allocation
    max_positions = int(portfolio_budget / np.median(min_position_values))

    if max_positions < 3:
        warnings.append(
            f"Budget allows approximately {max_positions} positions with current lot sizes. "
            f"Portfolio will be highly concentrated. "
            f"Consider: (1) Increase budget to ≥${np.median(min_position_values) * 5:,.0f}, "
            f"(2) Remove high lot-size assets, or (3) Accept concentration risk."
        )

    logging.info(f"  Estimated max positions: ~{max_positions}")

    # Raise errors (stop execution)
    if errors:
        raise ValueError("\n".join(["❌ MIQP Validation Failed:"] + errors))

    # Log warnings (continue with caution)
    for w in warnings:
        logging.warning(f"⚠️  {w}")

    if not warnings:
        logging.info(f"✅ MIQP validation passed (no warnings)")

    return True


def calculate_miqp_metrics(
    shares,
    prices_usd,
    mean_returns,
    cov_matrix,
    risk_free_rate,
    portfolio_budget,
    periods_per_year=252,
):
    """
    Calculate portfolio metrics from integer share counts.

    Parameters:
    -----------
    shares : np.array
        Integer share counts for each asset
    prices_usd : np.array
        Asset prices in USD
    mean_returns : np.array
        Daily log returns
    cov_matrix : np.ndarray
        Covariance matrix
    risk_free_rate : float
        Annual risk-free rate
    portfolio_budget : float
        Total budget (for utilization calculation)
    periods_per_year : int
        Annualization factor (252 for daily, 52 for weekly, 12 for monthly)

    Returns:
    --------
    tuple: (annual_return, annual_volatility, sharpe_ratio, total_value, utilization)
    """
    # Portfolio value (USD)
    total_value = np.sum(shares * prices_usd)

    if total_value == 0:
        return 0, 0, 0, 0, 0

    # Weights (from shares and prices)
    weights = (shares * prices_usd) / total_value

    # Annualized metrics
    annual_return = np.sum(weights * mean_returns) * periods_per_year
    annual_variance = weights @ cov_matrix @ weights * periods_per_year
    annual_volatility = np.sqrt(annual_variance)
    sharpe_ratio = (
        (annual_return - risk_free_rate) / annual_volatility
        if annual_volatility > 0
        else 0
    )

    # Budget utilization
    utilization = total_value / portfolio_budget if portfolio_budget > 0 else 0

    return annual_return, annual_volatility, sharpe_ratio, total_value, utilization


def solve_miqp_portfolio(
    prices_usd,
    mean_returns,
    cov_matrix,
    asset_names,
    portfolio_budget,
    lot_sizes,
    risk_free_rate=0.01,
    target_return=None,
    min_asset_weight=0.0,
    solver="SCIP",
    time_limit=600,
    periods_per_year=252,
):
    """
    Solve MIQP portfolio optimization for integer share counts.

    Uses cvxpy to formulate Mixed-Integer Quadratic Program with:
    - Integer decision variables (number of shares)
    - Lot size constraints (Tokyo: 100 shares, HK: varies per stock)
    - Budget constraint (total value ≤ portfolio_budget)
    - Optional target return constraint (for efficient frontier)

    Parameters:
    -----------
    prices_usd : np.array
        Asset prices in USD (already converted from native currencies)
    mean_returns : np.array
        Daily log returns
    cov_matrix : np.ndarray
        Covariance matrix (from Ledoit-Wolf)
    asset_names : list
        Ticker symbols
    portfolio_budget : float
        Maximum portfolio value in USD
    lot_sizes : dict
        {ticker: lot_size} (e.g., {'8002.T': 100})
    risk_free_rate : float
        Annual risk-free rate
    target_return : float or None
        If provided, minimize variance subject to return >= target (for frontier)
        If None, maximize Sharpe approximation
    min_asset_weight : float
        Minimum weight per asset (if > 0)
    solver : str
        'SCIP', 'CBC', 'GLPK', or 'GUROBI'
    time_limit : int
        Maximum solve time in seconds (default: 600 = 10 minutes)

    Returns:
    --------
    dict with:
        'shares': np.array (integers)
        'objective_value': float
        'solver_status': str
        'solver_used': str
        'solve_time': float

    Raises:
    -------
    RuntimeError if all solvers fail
    """
    try:
        import cvxpy as cp
    except ImportError:
        raise ImportError(
            "cvxpy not installed. Install with: pip install cvxpy pyscipopt cylp"
        )

    import time

    start_time = time.time()

    n_assets = len(prices_usd)

    logging.info(f"\n  Formulating MIQP problem ({n_assets} assets)...")

    # Decision variables: Integer auxiliary variables for lot sizes
    # k[i] = number of lots for asset i
    # shares[i] = k[i] * lot_size[i]
    k_vars = []
    shares_expr = []

    for i, ticker in enumerate(asset_names):
        lot_size = lot_sizes.get(ticker, 1)

        # k_i: number of lots (non-negative integer)
        k_i = cp.Variable(integer=True, nonneg=True, name=f"k_{ticker}")
        k_vars.append(k_i)

        # Actual shares = lot_size × k_i
        shares_i = lot_size * k_i
        shares_expr.append(shares_i)

    # Stack into single expression
    x = cp.hstack(shares_expr)

    # Portfolio value in USD
    portfolio_value = prices_usd @ x

    # Annual return (annualize returns based on data interval)
    annual_return = (mean_returns @ x) * periods_per_year

    # Annual variance (quadratic form)
    annual_variance = cp.quad_form(x, cov_matrix) * periods_per_year

    # Constraints
    constraints = [
        portfolio_value <= portfolio_budget,  # Budget constraint
    ]

    # Minimum weight constraint (if specified)
    if min_asset_weight > 0:
        for i in range(n_assets):
            constraints.append(
                prices_usd[i] * x[i] >= min_asset_weight * portfolio_budget
            )

    # Objective function
    if target_return is not None:
        # For efficient frontier: minimize variance subject to return >= target
        objective = cp.Minimize(annual_variance)
        constraints.append(annual_return >= target_return * portfolio_budget)
        logging.info(
            f"  Objective: Minimize variance subject to return >= {target_return:.4f}"
        )
    else:
        # Maximize Sharpe approximation using risk-aversion utility
        # max (return - risk_aversion × variance)
        risk_aversion = 1.0  # Tune this (0.5-2.0 typical)
        objective = cp.Maximize(annual_return - risk_aversion * annual_variance)
        logging.info(f"  Objective: Maximize Sharpe (risk aversion λ={risk_aversion})")

    logging.info(
        f"  Constraints: Budget ≤ ${portfolio_budget:,.0f}, Lot sizes, Non-negativity"
    )

    # Formulate problem
    problem = cp.Problem(objective, constraints)

    # Solve with fallback hierarchy
    # Note: Only SCIP and GUROBI support MIQP with quadratic objectives
    # CBC and GLPK do not support quadratic forms with integer variables
    solvers_to_try = [solver]

    # Add SCIP if not already first choice
    if "SCIP" not in solvers_to_try and "SCIP" in cp.installed_solvers():
        solvers_to_try.append("SCIP")

    # Add Gurobi if available (commercial, fastest)
    if "GUROBI" in cp.installed_solvers():
        solvers_to_try.append("GUROBI")

    # Remove duplicates while preserving order
    seen = set()
    solvers_to_try = [x for x in solvers_to_try if not (x in seen or seen.add(x))]

    logging.info(f"  Solver priority: {solvers_to_try}")

    for slv in solvers_to_try:
        if slv not in cp.installed_solvers():
            logging.debug(f"  Solver {slv} not installed, skipping")
            continue

        try:
            logging.info(f"  Attempting solve with {slv}...")

            problem.solve(
                solver=slv,
                verbose=False,
                # Note: time_limit not universally supported, handled via patience
            )

            elapsed = time.time() - start_time

            if problem.status in ["optimal", "optimal_inaccurate"]:
                # Extract integer shares from k variables
                shares_values = []
                for i, k_i in enumerate(k_vars):
                    lot_size = lot_sizes.get(asset_names[i], 1)

                    # k_i.value should be integer from MIQP solver
                    # Handle both scalar and array cases
                    if k_i.value is None:
                        k_value = 0
                    else:
                        k_scalar = float(np.squeeze(k_i.value))  # Ensure scalar
                        k_value = int(np.round(k_scalar))  # Round to nearest integer

                    # Shares = lot_size × k (guaranteed divisible by lot_size)
                    shares_i = lot_size * k_value

                    shares_values.append(shares_i)

                    # Debug log for lot size application
                    if shares_i > 0 and lot_size > 1:
                        logging.debug(
                            f"  {asset_names[i]}: k={k_value} × lot_size={lot_size} = {shares_i} shares"
                        )

                shares_int = np.array(shares_values)

                # Validate lot size compliance (critical check)
                lot_violations = []
                for i, ticker in enumerate(asset_names):
                    lot_size = lot_sizes.get(ticker, 1)
                    if shares_int[i] > 0 and shares_int[i] % lot_size != 0:
                        lot_violations.append(
                            f"{ticker}: {shares_int[i]} shares (not divisible by lot size {lot_size})"
                        )

                if lot_violations:
                    logging.error("🚨 LOT SIZE VIOLATIONS:")
                    for violation in lot_violations:
                        logging.error(f"  - {violation}")
                    raise RuntimeError(
                        "Lot size constraints violated. This should not happen with proper MIQP formulation. "
                        "Check solver implementation."
                    )

                logging.info(
                    f"  ✅ Solved with {slv}: status={problem.status}, time={elapsed:.1f}s"
                )
                logging.info(f"  Positions: {np.sum(shares_int > 0)} assets")

                return {
                    "shares": shares_int,
                    "objective_value": problem.value,
                    "solver_status": problem.status,
                    "solver_used": slv,
                    "solve_time": elapsed,
                }
            else:
                logging.warning(f"  Solver {slv} returned status: {problem.status}")

        except Exception as e:
            logging.error(f"  Solver {slv} failed: {e}")
            continue

    # All solvers failed
    raise RuntimeError(
        f"All MIQP solvers failed. Tried: {solvers_to_try}. "
        f"Problem may be infeasible. Check: (1) Budget sufficient, "
        f"(2) Lot sizes reasonable, (3) Constraints not conflicting."
    )


def generate_miqp_frontier(
    prices_usd,
    mean_returns,
    cov_matrix,
    asset_names,
    portfolio_budget,
    lot_sizes,
    exchange_rates,
    risk_free_rate,
    n_points=7,
    solver="SCIP",
    periods_per_year=252,
):
    """
    Generate exact MIQP efficient frontier.

    Solves n_points separate MIQP problems, each with target return constraint.
    Much slower than continuous frontier (5-10 min per point vs < 1 min total),
    but produces exact integer solutions that are directly tradeable.

    Parameters:
    -----------
    n_points : int
        Number of frontier points to solve (5-10 recommended)
        Each point takes 3-6 minutes → Total: 21-42 minutes

    Returns:
    --------
    list of dicts with frontier point results
    """
    logging.info(f"\n{'=' * 80}")
    logging.info(f"Generating MIQP Efficient Frontier ({n_points} exact points)")
    logging.info(f"{'=' * 80}")
    logging.info(f"⏱  Expected runtime: ~{n_points * 5} minutes")
    logging.info(f"   (Each point: 3-6 min with SCIP solver)")

    # Step 1: Find min volatility and max Sharpe portfolios
    logging.info(f"\nStep 1: Solve for boundary portfolios...")

    # Min volatility (set target_return = very low to effectively minimize variance)
    min_ret_target = -0.5  # Allow negative returns to find true min vol
    try:
        min_vol_result = solve_miqp_portfolio(
            prices_usd,
            mean_returns,
            cov_matrix,
            asset_names,
            portfolio_budget,
            lot_sizes,
            risk_free_rate,
            target_return=min_ret_target,
            solver=solver,
            periods_per_year=periods_per_year,
        )
        min_vol_ret, _, _, _, _ = calculate_miqp_metrics(
            min_vol_result["shares"],
            prices_usd,
            mean_returns,
            cov_matrix,
            risk_free_rate,
            portfolio_budget,
            periods_per_year,
        )
        logging.info(f"  Min volatility return: {min_vol_ret:.4f}")
    except Exception as e:
        logging.error(f"  Failed to solve min volatility: {e}")
        return []

    # Max Sharpe (no target return, maximize utility)
    try:
        max_sharpe_result = solve_miqp_portfolio(
            prices_usd,
            mean_returns,
            cov_matrix,
            asset_names,
            portfolio_budget,
            lot_sizes,
            risk_free_rate,
            target_return=None,  # Maximize Sharpe
            solver=solver,
            periods_per_year=periods_per_year,
        )
        max_sharpe_ret, _, _, _, _ = calculate_miqp_metrics(
            max_sharpe_result["shares"],
            prices_usd,
            mean_returns,
            cov_matrix,
            risk_free_rate,
            portfolio_budget,
            periods_per_year,
        )
        logging.info(f"  Max Sharpe return: {max_sharpe_ret:.4f}")
    except Exception as e:
        logging.error(f"  Failed to solve max Sharpe: {e}")
        return []

    # Step 2: Generate target returns
    # Ensure min < max (swap if needed)
    if min_vol_ret > max_sharpe_ret:
        target_returns = np.linspace(max_sharpe_ret, min_vol_ret, n_points)
    else:
        target_returns = np.linspace(min_vol_ret, max_sharpe_ret, n_points)

    logging.info(f"\nStep 2: Solving {n_points} frontier points...")
    logging.info(
        f"  Target returns: {target_returns[0]:.4f} to {target_returns[-1]:.4f}"
    )

    frontier_results = []

    # Step 3: Solve MIQP for each target
    for i, target_ret in enumerate(target_returns):
        logging.info(f"\n  Point {i + 1}/{n_points}: target return {target_ret:.4f}")

        try:
            result = solve_miqp_portfolio(
                prices_usd,
                mean_returns,
                cov_matrix,
                asset_names,
                portfolio_budget,
                lot_sizes,
                risk_free_rate,
                target_return=target_ret,
                solver=solver,
                periods_per_year=periods_per_year,
            )

            # Calculate actual metrics
            actual_ret, actual_vol, actual_sharpe, total_value, utilization = (
                calculate_miqp_metrics(
                    result["shares"],
                    prices_usd,
                    mean_returns,
                    cov_matrix,
                    risk_free_rate,
                    portfolio_budget,
                    periods_per_year,
                )
            )

            frontier_results.append(
                {
                    "point_number": i + 1,
                    "target_return": target_ret,
                    "actual_return": actual_ret,
                    "volatility": actual_vol,
                    "sharpe_ratio": actual_sharpe,
                    "shares": result["shares"],
                    "total_value": total_value,
                    "budget_utilization": utilization,
                    "solve_time": result["solve_time"],
                    "solver_status": result["solver_status"],
                    "solver_used": result["solver_used"],
                }
            )

            logging.info(
                f"    ✅ Return={actual_ret:.4f}, Vol={actual_vol:.4f}, "
                f"Sharpe={actual_sharpe:.4f} ({result['solve_time']:.1f}s)"
            )

        except Exception as e:
            logging.error(f"    ❌ Failed: {e}")
            logging.info(f"    Skipping point {i + 1}, continuing to next...")
            continue

    logging.info(
        f"\n✅ MIQP Frontier complete: {len(frontier_results)}/{n_points} points solved"
    )

    total_time = sum(pt["solve_time"] for pt in frontier_results)
    logging.info(
        f"   Total solve time: {total_time:.1f}s ({total_time / 60:.1f} minutes)"
    )

    return frontier_results


# --- Main Portfolio Optimization Function ---
def perform_portfolio_optimization(
    returns_df,
    num_portfolios,
    risk_free_rate,
    output_dir,
    timestamp,
    target_volatility=None,
    min_asset_weight=0.0,
    fixed_weights=None,
    # MIQP mode parameters (NEW):
    optimization_mode="continuous",
    portfolio_budget=50000.0,
    lot_sizes=None,
    exchange_rates=None,
    prices_dict=None,  # For MIQP: {ticker: latest_price}
    miqp_solver="SCIP",
    frontier_points=7,
    # Reference portfolios from portfolio exploration log:
    reference_portfolios=None,
    # Interval support:
    periods_per_year=252,
    # Reproducibility:
    seed=42,
):
    """
    Performs portfolio optimization with two modes:

    1. Continuous mode (default): Fractional weights, fast, research/backtesting
    2. MIQP mode: Integer shares, lot sizes, multi-currency, production trading

    MIQP Mode (NEW):
    ----------------
    - Optimizes for integer share counts (directly tradeable)
    - Respects exchange lot size requirements (Tokyo: 100 shares, etc.)
    - Multi-currency support (USD, JPY, GBP, HKD, EUR, AUD, CAD, SGD)
    - Exact efficient frontier (5-10 points, ~30-60 min total)

    Original Continuous Mode:
    --------------------------
    - Uses scipy.optimize and visualizes the results
    - Combines with Monte Carlo simulation for visualization
    - Can find portfolio for specific target volatility

    Parameters:
    -----------
    returns_df : pd.DataFrame
        DataFrame of logarithmic returns, where each column represents an asset.
    num_portfolios : int
        Number of random portfolios to simulate for visualization.
    risk_free_rate : float
        Annualized risk-free rate for Sharpe ratio calculation.
    output_dir : str
        Directory to save the portfolio optimization plot.
    timestamp : str
        Unique timestamp for filenames.
    target_volatility : float, optional
        An annualized target volatility to find a portfolio for. If None, this step is skipped.
    min_asset_weight : float, optional
        Minimum weight for each asset in the portfolio. Default is 0.0 (no minimum).
    fixed_weights : dict, optional
        Dictionary mapping asset names to their fixed weights.
        Example: {'SPY': 0.3, 'GLD': 0.2} fixes SPY at 30% and GLD at 20%.
        The remaining assets will be optimized to fill the remaining allocation.

    Returns:
    --------
    dict
        A dictionary containing results for max Sharpe, min volatility, and
        optionally target volatility portfolios.
    """
    if returns_df.empty:
        logging.warning("No data available to perform portfolio optimization.")
        return {}

    logging.info(
        f"\n--- Performing Portfolio Optimization on {len(returns_df.columns)} Assets ---"
    )

    mean_returns = returns_df.mean()

    # Use Ledoit-Wolf shrinkage estimator for more stable covariance matrix estimation
    logging.info("\n--- Computing Covariance Matrix using Ledoit-Wolf Shrinkage ---")
    lw = LedoitWolf()
    lw.fit(returns_df)
    cov_matrix = pd.DataFrame(
        lw.covariance_, index=returns_df.columns, columns=returns_df.columns
    )
    shrinkage_intensity = lw.shrinkage_
    logging.info(f"  Shrinkage intensity: {shrinkage_intensity:.4f}")
    logging.info(f"  (0 = no shrinkage, 1 = full shrinkage to target)")
    logging.info(f"  Condition number: {np.linalg.cond(cov_matrix):.2f}")

    num_assets = len(returns_df.columns)
    asset_names = returns_df.columns.tolist()

    # =========================================================================
    # MIQP MODE BRANCH (Integer Share Optimization)
    # =========================================================================
    if optimization_mode == "miqp":
        logging.info(f"\n{'=' * 80}")
        logging.info("MIQP MODE: Integer Share Optimization")
        logging.info(f"{'=' * 80}")
        logging.info(f"Portfolio Budget: ${portfolio_budget:,.2f} USD")
        logging.info(f"Solver: {miqp_solver}")
        logging.info(f"Frontier Points: {frontier_points}")

        # MIQP mode requires prices
        if prices_dict is None:
            raise ValueError(
                "MIQP mode requires prices_dict. This should be passed from main_workflow. "
                "Make sure prices are extracted from CSV before calling perform_portfolio_optimization."
            )

        # Exchange rates: Default to USD-only if not provided
        if exchange_rates is None:
            exchange_rates = {"USD": 1.0}
            logging.info("No exchange rates provided, assuming all assets are USD")

        logging.info(f"\nUsing provided prices for {len(prices_dict)} assets")
        # Show sample
        for ticker in list(prices_dict.keys())[:5]:
            logging.info(f"  {ticker}: {prices_dict[ticker]:.2f}")

        # Validate inputs
        validate_miqp_inputs(
            asset_names, prices_dict, portfolio_budget, lot_sizes or {}, exchange_rates
        )

        # Normalize prices to USD
        prices_usd = normalize_to_usd(prices_dict, asset_names, exchange_rates)

        # Solve MIQP for max Sharpe
        logging.info(f"\n{'=' * 80}")
        logging.info("Solving MIQP for Maximum Sharpe Ratio")
        logging.info(f"{'=' * 80}")

        try:
            max_sharpe_miqp = solve_miqp_portfolio(
                prices_usd,
                mean_returns.values,
                cov_matrix.values,
                asset_names,
                portfolio_budget,
                lot_sizes or {},
                risk_free_rate,
                target_return=None,
                solver=miqp_solver,
                periods_per_year=periods_per_year,
            )

            # Calculate metrics
            ret, vol, sharpe, total_val, util = calculate_miqp_metrics(
                max_sharpe_miqp["shares"],
                prices_usd,
                mean_returns.values,
                cov_matrix.values,
                risk_free_rate,
                portfolio_budget,
                periods_per_year,
            )

            logging.info(f"\nMaximum Sharpe MIQP Portfolio:")
            logging.info(f"  Return:      {ret:.4f} ({ret * 100:.2f}%)")
            logging.info(f"  Volatility:  {vol:.4f} ({vol * 100:.2f}%)")
            logging.info(f"  Sharpe:      {sharpe:.4f}")
            logging.info(f"  Total Value: ${total_val:,.2f}")
            logging.info(f"  Budget Used: {util:.1%}")
            logging.info(
                f"  Solver:      {max_sharpe_miqp['solver_used']} ({max_sharpe_miqp['solve_time']:.1f}s)"
            )

            # Display share breakdown
            shares = max_sharpe_miqp["shares"]
            n_positions = np.sum(shares > 0)

            logging.info(f"\n  Portfolio Positions ({n_positions} assets):")
            logging.info(
                f"  {'Ticker':<15} {'Shares':<10} {'Price USD':<12} {'Value USD':<12} {'Weight':<8}"
            )
            logging.info(f"  {'-' * 15} {'-' * 10} {'-' * 12} {'-' * 12} {'-' * 8}")

            for i, ticker in enumerate(asset_names):
                if shares[i] > 0:
                    share_count = shares[i]
                    price = prices_usd[i]
                    value = share_count * price
                    weight = value / total_val if total_val > 0 else 0

                    logging.info(
                        f"  {ticker:<15} {share_count:<10d} "
                        f"${price:<11,.2f} ${value:<11,.2f} {weight:<7.1%}"
                    )

            # Calculate MIQP portfolio weights for comprehensive metrics
            miqp_weights = (
                (shares * prices_usd) / total_val
                if total_val > 0
                else np.zeros_like(shares)
            )
            miqp_comprehensive = calculate_comprehensive_portfolio_metrics(
                miqp_weights, returns_df, risk_free_rate, periods_per_year
            )
            log_comprehensive_metrics(
                miqp_comprehensive, "Maximum Sharpe MIQP Portfolio"
            )

        except Exception as e:
            logging.error(f"MIQP optimization failed: {e}")
            raise

        # Generate MIQP efficient frontier
        if frontier_points > 0:
            frontier_miqp = generate_miqp_frontier(
                prices_usd,
                mean_returns.values,
                cov_matrix.values,
                asset_names,
                portfolio_budget,
                lot_sizes or {},
                exchange_rates,
                risk_free_rate,
                n_points=frontier_points,
                solver=miqp_solver,
                periods_per_year=periods_per_year,
            )
        else:
            frontier_miqp = []

        # Return MIQP results with comprehensive metrics
        results_dict = {
            "mode": "miqp",
            "max_sharpe_optimized": {
                "Return": ret,
                "Volatility": vol,
                "Sharpe Ratio": sharpe,
                "Shares": max_sharpe_miqp["shares"].tolist(),
                "Total Value": total_val,
                "Budget Utilization": util,
                "Solver": max_sharpe_miqp["solver_used"],
                "Solve Time": max_sharpe_miqp["solve_time"],
                # Comprehensive metrics
                "Sortino Ratio": miqp_comprehensive["sortino_ratio"],
                "Calmar Ratio": miqp_comprehensive["calmar_ratio"],
                "Omega Ratio": miqp_comprehensive["omega_ratio"],
                "VaR 95%": miqp_comprehensive["var_95"],
                "CVaR 95%": miqp_comprehensive["cvar_95"],
                "Max Drawdown": miqp_comprehensive["max_drawdown"],
                "PSR": miqp_comprehensive["psr"],
                "Skewness": miqp_comprehensive["skewness"],
                "Kurtosis": miqp_comprehensive["kurtosis"],
                "Top 3 Concentration": miqp_comprehensive["top3_concentration"],
                "Herfindahl Index": miqp_comprehensive["herfindahl_index"],
            },
            "efficient_frontier_miqp": frontier_miqp,
            "asset_names": asset_names,
            "prices_usd": prices_usd.tolist(),
            "exchange_rates": exchange_rates,
            "portfolio_budget": portfolio_budget,
        }

        logging.info(f"\n✅ MIQP optimization complete")
        return results_dict

    # =========================================================================
    # CONTINUOUS MODE (Original Logic - UNCHANGED)
    # =========================================================================

    # --- Handle Fixed Weights ---
    fixed_indices = []
    fixed_values = []
    free_indices = []
    total_fixed_weight = 0.0

    if fixed_weights:
        logging.info(f"\n--- Applying Fixed Weights ---")
        for asset_name, fixed_weight in fixed_weights.items():
            if asset_name in asset_names:
                idx = asset_names.index(asset_name)
                fixed_indices.append(idx)
                fixed_values.append(fixed_weight)
                total_fixed_weight += fixed_weight
                logging.info(
                    f"  {asset_name}: Fixed at {fixed_weight:.4f} ({fixed_weight * 100:.2f}%)"
                )
            else:
                logging.warning(
                    f"  {asset_name}: Not found in portfolio assets, skipping fixed weight"
                )

        if total_fixed_weight >= 1.0:
            raise ValueError(
                f"Total fixed weights ({total_fixed_weight:.4f}) must be less than 1.0"
            )

        # Identify free indices (assets that can be optimized)
        free_indices = [i for i in range(num_assets) if i not in fixed_indices]
        logging.info(
            f"  Total fixed allocation: {total_fixed_weight:.4f} ({total_fixed_weight * 100:.2f}%)"
        )
        logging.info(
            f"  Remaining allocation for optimization: {1 - total_fixed_weight:.4f} ({(1 - total_fixed_weight) * 100:.2f}%)"
        )
        logging.info(f"  Assets to optimize: {[asset_names[i] for i in free_indices]}")
    else:
        free_indices = list(range(num_assets))

    # --- Define Constraints and Bounds for Optimization ---
    if fixed_weights and fixed_indices:
        # Create modified constraints that account for fixed weights
        # The sum of free weights must equal (1 - total_fixed_weight)
        constraints = {
            "type": "eq",
            "fun": lambda x: np.sum(x) - (1 - total_fixed_weight),
        }

        # Only create bounds for free assets
        num_free_assets = len(free_indices)
        if num_free_assets > 0 and min_asset_weight * num_free_assets > (
            1 - total_fixed_weight
        ):
            raise ValueError(
                f"min_asset_weight ({min_asset_weight}) is too high for {num_free_assets} free assets with {1 - total_fixed_weight:.4f} available allocation."
            )

        bounds = tuple(
            (min_asset_weight, 1 - total_fixed_weight) for _ in range(num_free_assets)
        )
    else:
        # Standard constraints and bounds when no fixed weights
        constraints = {"type": "eq", "fun": lambda x: np.sum(x) - 1}

        # Bounds: Weights for each asset must be between min_asset_weight and 1
        if not (0 <= min_asset_weight <= 1):
            raise ValueError("min_asset_weight must be between 0 and 1.")
        if min_asset_weight * num_assets > 1:
            raise ValueError(
                f"min_asset_weight ({min_asset_weight}) is too high for {num_assets} assets. Sum of minimum weights exceeds 1."
            )

        bounds = tuple((min_asset_weight, 1) for asset in range(num_assets))

    # Initial guess: Equally weighted portfolio (or adjusted for min_asset_weight and fixed weights)
    if fixed_weights and fixed_indices:
        # For optimization with fixed weights, initial guess is only for free assets
        num_free_assets = len(free_indices)
        if num_free_assets > 0:
            initial_weights = np.array(
                num_free_assets * [(1 - total_fixed_weight) / num_free_assets]
            )
            if min_asset_weight > 0 and (initial_weights < min_asset_weight).any():
                initial_weights = np.full(num_free_assets, min_asset_weight)
                remaining_weight = (1 - total_fixed_weight) - np.sum(initial_weights)
                if remaining_weight > 0:
                    initial_weights += remaining_weight / num_free_assets
                initial_weights /= np.sum(initial_weights)
                initial_weights *= 1 - total_fixed_weight
        else:
            # No free assets to optimize
            logging.warning("No free assets to optimize. All weights are fixed.")
            # Return early with fixed weights only
            full_fixed_weights = np.zeros(num_assets)
            for i, idx in enumerate(fixed_indices):
                full_fixed_weights[idx] = fixed_values[i]
            return {
                "fixed_only": True,
                "weights": full_fixed_weights.tolist(),
                "asset_names": asset_names,
            }
    else:
        initial_weights = np.array(num_assets * [1.0 / num_assets])
        # Ensure initial weights respect min_asset_weight, if not, adjust
        if min_asset_weight > 0 and (initial_weights < min_asset_weight).any():
            logging.info(
                f"Adjusting initial weights to respect min_asset_weight of {min_asset_weight}."
            )
            initial_weights = np.full(num_assets, min_asset_weight)
            remaining_weight = 1.0 - np.sum(initial_weights)
            # Distribute remaining_weight if any, for example, evenly
            if remaining_weight > 0:
                initial_weights += remaining_weight / num_assets
            # Re-normalize just to be safe, though it should sum to 1
            initial_weights /= np.sum(initial_weights)

    # Create wrapper functions if we have fixed weights
    if fixed_weights and fixed_indices:
        # Wrapper functions that expand free weights to full weights for calculations
        def min_func_sharpe_fixed(free_weights):
            full_weights = expand_weights(
                free_weights, fixed_indices, fixed_values, num_assets
            )
            return min_func_sharpe(
                full_weights, mean_returns, cov_matrix, risk_free_rate, periods_per_year
            )

        def min_func_volatility_fixed(free_weights):
            full_weights = expand_weights(
                free_weights, fixed_indices, fixed_values, num_assets
            )
            return min_func_volatility(
                full_weights, mean_returns, cov_matrix, periods_per_year
            )

        def max_func_return_fixed(free_weights):
            full_weights = expand_weights(
                free_weights, fixed_indices, fixed_values, num_assets
            )
            return max_func_return(
                full_weights, mean_returns, cov_matrix, risk_free_rate, periods_per_year
            )

        # Use the wrapper functions for optimization
        sharpe_func = min_func_sharpe_fixed
        vol_func = min_func_volatility_fixed
        ret_func = max_func_return_fixed
    else:
        # Use original functions
        sharpe_func = lambda w: min_func_sharpe(
            w, mean_returns, cov_matrix, risk_free_rate, periods_per_year
        )
        vol_func = lambda w: min_func_volatility(
            w, mean_returns, cov_matrix, periods_per_year
        )
        ret_func = lambda w: max_func_return(
            w, mean_returns, cov_matrix, risk_free_rate, periods_per_year
        )

    # --- Optimize for Maximum Sharpe Ratio ---
    logging.info("\n--- Optimizing for Maximum Sharpe Ratio ---")
    optimal_sharpe = sco.minimize(
        sharpe_func,
        initial_weights,
        method="SLSQP",
        bounds=bounds,
        constraints=constraints,
    )

    # Extract and expand weights if using fixed weights
    if fixed_weights and fixed_indices:
        max_sharpe_weights = expand_weights(
            optimal_sharpe["x"], fixed_indices, fixed_values, num_assets
        )
    else:
        max_sharpe_weights = optimal_sharpe["x"]
    max_sharpe_metrics = statistics(
        max_sharpe_weights, mean_returns, cov_matrix, risk_free_rate, periods_per_year
    )

    max_sharpe_return = max_sharpe_metrics[0]
    max_sharpe_volatility = max_sharpe_metrics[1]
    max_sharpe_ratio = max_sharpe_metrics[2]

    logging.info("\nMaximum Sharpe Ratio Portfolio (Optimized):")
    logging.info(f"  Return: {max_sharpe_return:.4f}")
    logging.info(f"  Volatility: {max_sharpe_volatility:.4f}")
    logging.info(f"  Sharpe Ratio: {max_sharpe_ratio:.4f}")
    logging.info("  Weights:")
    for asset, weight in zip(returns_df.columns, max_sharpe_weights):
        logging.info(f"    {asset}: {weight:.4f}")

    # Calculate and log comprehensive metrics for Max Sharpe portfolio
    max_sharpe_comprehensive = calculate_comprehensive_portfolio_metrics(
        max_sharpe_weights, returns_df, risk_free_rate, periods_per_year
    )
    log_comprehensive_metrics(max_sharpe_comprehensive, "Maximum Sharpe Portfolio")

    # --- Optimize for Minimum Volatility ---
    logging.info("\n--- Optimizing for Minimum Volatility ---")
    optimal_volatility = sco.minimize(
        vol_func,
        initial_weights,
        method="SLSQP",
        bounds=bounds,
        constraints=constraints,
    )

    # Extract and expand weights if using fixed weights
    if fixed_weights and fixed_indices:
        min_vol_weights = expand_weights(
            optimal_volatility["x"], fixed_indices, fixed_values, num_assets
        )
    else:
        min_vol_weights = optimal_volatility["x"]
    min_vol_metrics = statistics(
        min_vol_weights, mean_returns, cov_matrix, risk_free_rate, periods_per_year
    )  # Use risk_free_rate here for full metrics
    min_vol_return = min_vol_metrics[0]
    min_vol_volatility = min_vol_metrics[1]
    min_vol_sharpe_ratio = min_vol_metrics[2]
    logging.info("\nMinimum Volatility Portfolio (Optimized):")
    logging.info(f"  Return: {min_vol_return:.4f}")
    logging.info(f"  Volatility: {min_vol_volatility:.4f}")
    logging.info(f"  Sharpe Ratio: {min_vol_sharpe_ratio:.4f}")
    logging.info("  Weights:")
    for asset, weight in zip(returns_df.columns, min_vol_weights):
        logging.info(f"    {asset}: {weight:.4f}")

    # Calculate and log comprehensive metrics for Min Vol portfolio
    min_vol_comprehensive = calculate_comprehensive_portfolio_metrics(
        min_vol_weights, returns_df, risk_free_rate, periods_per_year
    )
    log_comprehensive_metrics(min_vol_comprehensive, "Minimum Volatility Portfolio")

    # --- Monte Carlo Simulation (for visualization of the efficient frontier points) ---
    logging.info(
        f"\n--- Running Monte Carlo Simulation for Visualization ({num_portfolios} portfolios) ---"
    )
    np.random.seed(seed)  # Seed for reproducible Monte Carlo weight sampling
    results = np.zeros((3, num_portfolios))  # For return, volatility, sharpe ratio
    all_mc_weights = np.zeros(
        (num_portfolios, num_assets)
    )  # To store weights of MC portfolios

    for i in range(num_portfolios):
        if fixed_weights and fixed_indices:
            # Generate random weights only for free assets
            num_free_assets = len(free_indices)
            if num_free_assets > 0:
                free_weights = np.random.uniform(min_asset_weight, 1.0, num_free_assets)
                free_weights = (
                    free_weights / np.sum(free_weights) * (1 - total_fixed_weight)
                )  # Normalize to remaining allocation
                weights = expand_weights(
                    free_weights, fixed_indices, fixed_values, num_assets
                )
            else:
                # All weights are fixed
                weights = np.zeros(num_assets)
                for j, idx in enumerate(fixed_indices):
                    weights[idx] = fixed_values[j]
        else:
            weights = np.random.uniform(
                min_asset_weight, 1.0, num_assets
            )  # Generate random weights respecting min_asset_weight
            weights /= np.sum(weights)  # Normalize weights

        all_mc_weights[i, :] = weights  # Store weights

        port_metrics = statistics(
            weights, mean_returns, cov_matrix, risk_free_rate, periods_per_year
        )
        results[0, i] = port_metrics[1]  # Volatility
        results[1, i] = port_metrics[0]  # Return
        results[2, i] = port_metrics[2]  # Sharpe Ratio

    portfolio_results_df = pd.DataFrame(
        results.T, columns=["Volatility", "Return", "Sharpe_Ratio"]
    )
    portfolio_results_df["Weights"] = list(all_mc_weights)  # Add weights as a column

    # --- Calculate Efficient Frontier (Analytical) ---
    logging.info("\n--- Calculating Analytical Efficient Frontier ---")
    # Define a range of target returns for the efficient frontier curve
    # Use returns from min volatility up to max sharpe for the efficient frontier curve
    # Ensure min_vol_return <= max_sharpe_return for linspace to work correctly
    # Adjusted to ensure target_returns_ef is always in ascending order for consistent plotting
    if min_vol_return > max_sharpe_return:
        target_returns_ef = np.linspace(max_sharpe_return, min_vol_return, 100)
    else:
        target_returns_ef = np.linspace(min_vol_return, max_sharpe_return, 100)

    efficient_frontier_volatilities = []
    efficient_frontier_returns = []
    efficient_frontier_weights = []  # Store weights for analytical frontier points

    for trets in target_returns_ef:
        # Constraint for target return: portfolio return must equal trets
        if fixed_weights and fixed_indices:
            # For fixed weights, we need to work with free weights only
            def target_return_constraint_func(free_weights):
                full_weights = expand_weights(
                    free_weights, fixed_indices, fixed_values, num_assets
                )
                return (
                    statistics(
                        full_weights,
                        mean_returns,
                        cov_matrix,
                        risk_free_rate,
                        periods_per_year,
                    )[0]
                    - trets
                )

            target_return_constraint = {
                "type": "eq",
                "fun": target_return_constraint_func,
            }
        else:
            target_return_constraint = {
                "type": "eq",
                "fun": lambda x: (
                    statistics(
                        x, mean_returns, cov_matrix, risk_free_rate, periods_per_year
                    )[0]
                    - trets
                ),
            }

        # Combine with existing sum-of-weights constraint
        all_constraints_ef = (constraints, target_return_constraint)

        # Minimize volatility for the given target return
        opt = sco.minimize(
            vol_func,
            initial_weights,
            method="SLSQP",
            bounds=bounds,
            constraints=all_constraints_ef,
        )

        if opt.success:
            # Expand weights if using fixed weights
            if fixed_weights and fixed_indices:
                opt_weights = expand_weights(
                    opt["x"], fixed_indices, fixed_values, num_assets
                )
            else:
                opt_weights = opt["x"]

            efficient_frontier_volatilities.append(
                statistics(
                    opt_weights,
                    mean_returns,
                    cov_matrix,
                    risk_free_rate,
                    periods_per_year,
                )[1]
            )
            efficient_frontier_returns.append(trets)
            efficient_frontier_weights.append(opt_weights)

    # --- Optimize for Target Volatility (if provided) ---
    target_vol_portfolio_data = None
    second_best_target_vol_portfolio_data = None
    third_best_target_vol_portfolio_data = None

    # New: Data for Monte Carlo portfolios close to target volatility
    top_mc_target_vol_portfolios = []

    if target_volatility is not None:
        logging.info(
            f"\n--- Optimizing for Target Volatility: {target_volatility:.4f} ---"
        )
        # Constraint for target volatility: portfolio volatility must equal target_volatility
        if fixed_weights and fixed_indices:
            # For fixed weights, we need to work with free weights only
            def target_vol_constraint_func(free_weights):
                full_weights = expand_weights(
                    free_weights, fixed_indices, fixed_values, num_assets
                )
                return (
                    statistics(
                        full_weights,
                        mean_returns,
                        cov_matrix,
                        risk_free_rate,
                        periods_per_year,
                    )[1]
                    - target_volatility
                )

            target_vol_constraint = {"type": "eq", "fun": target_vol_constraint_func}
        else:
            target_vol_constraint = {
                "type": "eq",
                "fun": lambda x: (
                    statistics(
                        x, mean_returns, cov_matrix, risk_free_rate, periods_per_year
                    )[1]
                    - target_volatility
                ),
            }

        # Combine with existing sum-of-weights and bounds
        all_constraints_target_vol = (constraints, target_vol_constraint)

        # Maximize return for the given target volatility
        opt_target_vol = sco.minimize(
            ret_func,
            initial_weights,
            method="SLSQP",
            bounds=bounds,
            constraints=all_constraints_target_vol,
        )

        if opt_target_vol.success:
            # Expand weights if using fixed weights
            if fixed_weights and fixed_indices:
                target_vol_weights = expand_weights(
                    opt_target_vol["x"], fixed_indices, fixed_values, num_assets
                )
            else:
                target_vol_weights = opt_target_vol["x"]
            target_vol_metrics = statistics(
                target_vol_weights,
                mean_returns,
                cov_matrix,
                risk_free_rate,
                periods_per_year,
            )

            target_vol_return = target_vol_metrics[0]
            target_vol_actual_volatility = target_vol_metrics[
                1
            ]  # Should be very close to target_volatility
            target_vol_sharpe_ratio = target_vol_metrics[2]

            logging.info(
                f"\nTarget Volatility Portfolio (Optimized for {target_volatility:.4f} volatility):"
            )
            logging.info(f"  Return: {target_vol_return:.4f}")
            logging.info(f"  Volatility: {target_vol_actual_volatility:.4f}")
            logging.info(f"  Sharpe Ratio: {target_vol_sharpe_ratio:.4f}")
            logging.info("  Weights:")
            for asset, weight in zip(returns_df.columns, target_vol_weights):
                logging.info(f"    {asset}: {weight:.4f}")

            target_vol_portfolio_data = {
                "Return": target_vol_return,
                "Volatility": target_vol_actual_volatility,
                "Sharpe Ratio": target_vol_sharpe_ratio,
                "Weights": target_vol_weights,
            }

            # Calculate and log comprehensive metrics for Target Volatility portfolio
            target_vol_comprehensive = calculate_comprehensive_portfolio_metrics(
                target_vol_weights, returns_df, risk_free_rate, periods_per_year
            )
            log_comprehensive_metrics(
                target_vol_comprehensive,
                f"Target Volatility Portfolio ({target_volatility:.2%})",
            )

            # --- Find top Monte Carlo portfolios near target volatility ---
            vol_tolerance_mc = (
                0.01  # A tighter tolerance for MC portfolios near the target
            )

            # Filter Monte Carlo portfolios within a small band around the target volatility
            filtered_mc_portfolios = portfolio_results_df[
                (
                    portfolio_results_df["Volatility"]
                    >= target_volatility - vol_tolerance_mc
                )
                & (
                    portfolio_results_df["Volatility"]
                    <= target_volatility + vol_tolerance_mc
                )
            ].copy()  # Use .copy() to avoid SettingWithCopyWarning

            if not filtered_mc_portfolios.empty:
                # Sort by Sharpe Ratio (descending) then Return (descending)
                filtered_mc_portfolios = filtered_mc_portfolios.sort_values(
                    by=["Sharpe_Ratio", "Return"], ascending=[False, False]
                )

                # Select distinct top Monte Carlo portfolios
                mc_distinct_threshold = 0.05  # For weight distinctness

                # Add the primary optimized target_vol_portfolio as the first "best" candidate
                # This is because the optimized one is the 'best' *by definition* at that volatility target
                temp_top_portfolios = [
                    {
                        "Return": target_vol_portfolio_data["Return"],
                        "Volatility": target_vol_portfolio_data["Volatility"],
                        "Sharpe_Ratio": target_vol_portfolio_data["Sharpe Ratio"],
                        "Weights": target_vol_portfolio_data["Weights"],
                    }
                ]

                # Now add distinct Monte Carlo portfolios
                for idx, row in filtered_mc_portfolios.iterrows():
                    is_distinct = True
                    current_mc_weights = np.array(
                        row["Weights"]
                    )  # Ensure it's a numpy array for comparison

                    for existing_p in temp_top_portfolios:
                        # Check if the current MC portfolio is too similar to an already selected 'best' one
                        if not are_weights_distinct(
                            current_mc_weights,
                            existing_p["Weights"],
                            mc_distinct_threshold,
                        ):
                            is_distinct = False
                            break

                    if is_distinct:
                        temp_top_portfolios.append(
                            {
                                "Return": row["Return"],
                                "Volatility": row["Volatility"],
                                "Sharpe_Ratio": row["Sharpe_Ratio"],
                                "Weights": current_mc_weights,
                            }
                        )
                    if (
                        len(temp_top_portfolios) >= 4
                    ):  # Get up to 3 additional distinct MC portfolios (total of 4, including the optimized)
                        break

                # The first one is always the optimized one. Take the next few distinct MC ones.
                top_mc_target_vol_portfolios = temp_top_portfolios[1:]

                if len(top_mc_target_vol_portfolios) > 0:
                    logging.info(
                        f"\nTop Monte Carlo Portfolios near Target Volatility ({target_volatility:.4f}):"
                    )
                    for i, p in enumerate(top_mc_target_vol_portfolios):
                        logging.info(f"  MC Portfolio #{i + 1}:")
                        logging.info(f"    Return: {p['Return']:.4f}")
                        logging.info(f"    Volatility: {p['Volatility']:.4f}")
                        logging.info(f"    Sharpe Ratio: {p['Sharpe_Ratio']:.4f}")
                        logging.info("    Weights:")
                        for asset, weight in zip(returns_df.columns, p["Weights"]):
                            logging.info(f"      {asset}: {weight:.4f}")

                        # Calculate and log comprehensive metrics for each MC portfolio
                        mc_comprehensive = calculate_comprehensive_portfolio_metrics(
                            p["Weights"], returns_df, risk_free_rate, periods_per_year
                        )
                        log_comprehensive_metrics(
                            mc_comprehensive,
                            f"MC Portfolio #{i + 1} (Target Vol {target_volatility:.2%})",
                        )

            # The logic for 2nd and 3rd best from Efficient Frontier remains useful
            # (as the "best" for that volatility *on the curve*)
            # Collect all efficient frontier points near the target volatility
            all_ef_portfolios = []
            for i in range(len(efficient_frontier_volatilities)):
                vol = efficient_frontier_volatilities[i]
                ret = efficient_frontier_returns[i]
                weights = efficient_frontier_weights[i]
                sharpe = statistics(
                    weights, mean_returns, cov_matrix, risk_free_rate, periods_per_year
                )[2]
                all_ef_portfolios.append(
                    {
                        "Return": ret,
                        "Volatility": vol,
                        "Sharpe Ratio": sharpe,
                        "Weights": weights,
                    }
                )
            # Filter for portfolios close to the target volatility
            vol_tolerance = (
                0.005  # Search within +/- 0.5% of the target volatility for EF points
            )
            nearby_ef_portfolios = [
                p
                for p in all_ef_portfolios
                if abs(p["Volatility"] - target_vol_actual_volatility) <= vol_tolerance
            ]

            # Sort by Sharpe Ratio (descending), then Return (descending), then Volatility (ascending)
            nearby_ef_portfolios.sort(
                key=lambda x: (x["Sharpe Ratio"], x["Return"], -x["Volatility"]),
                reverse=True,
            )

            # Select distinct portfolios, ensuring we don't pick the *exact same* optimized one again if it happens to be on EF
            selected_distinct_ef_portfolios = []
            ef_weight_distinctness_threshold = (
                0.001  # A smaller threshold for EF points as they are 'analytical'
            )

            # Check if the primary optimized target_vol_portfolio is already effectively on the EF
            is_optimized_on_ef = False
            for p_ef in nearby_ef_portfolios:
                if (
                    abs(p_ef["Return"] - target_vol_portfolio_data["Return"]) < 1e-4
                    and abs(
                        p_ef["Volatility"] - target_vol_portfolio_data["Volatility"]
                    )
                    < 1e-4
                ):
                    is_optimized_on_ef = True
                    break

            if (
                not is_optimized_on_ef
            ):  # If the optimized point is NOT on the EF, add it first.
                # This ensures the 'optimized' one is correctly identified as the 'best'
                selected_distinct_ef_portfolios.append(target_vol_portfolio_data)

            for p in nearby_ef_portfolios:
                is_distinct_from_selected = True
                for existing_p in selected_distinct_ef_portfolios:
                    # Check for metric similarity and weight similarity
                    metrics_similar = (
                        abs(p["Return"] - existing_p["Return"]) < 1e-4
                        and abs(p["Volatility"] - existing_p["Volatility"]) < 1e-4
                        and abs(p["Sharpe Ratio"] - existing_p["Sharpe Ratio"]) < 1e-4
                    )
                    weights_too_similar = not are_weights_distinct(
                        p["Weights"],
                        existing_p["Weights"],
                        ef_weight_distinctness_threshold,
                    )

                    if metrics_similar and weights_too_similar:
                        is_distinct_from_selected = False
                        break

                if is_distinct_from_selected:
                    selected_distinct_ef_portfolios.append(p)

                if (
                    len(selected_distinct_ef_portfolios) >= 3
                ):  # We need up to 3 best distinct portfolios
                    break

            # Re-assign based on the selected_distinct_ef_portfolios list
            # The 'Best' is already handled by target_vol_portfolio_data
            if len(selected_distinct_ef_portfolios) > 1:
                second_best_target_vol_portfolio_data = selected_distinct_ef_portfolios[
                    1
                ]
                logging.info(
                    f"\nSecond Best Target Volatility Portfolio (from Efficient Frontier near {target_volatility:.4f}):"
                )
                logging.info(
                    f"  Return: {second_best_target_vol_portfolio_data['Return']:.4f}"
                )
                logging.info(
                    f"  Volatility: {second_best_target_vol_portfolio_data['Volatility']:.4f}"
                )
                logging.info(
                    f"  Sharpe Ratio: {second_best_target_vol_portfolio_data['Sharpe Ratio']:.4f}"
                )
                logging.info("  Weights:")
                for asset, weight in zip(
                    returns_df.columns, second_best_target_vol_portfolio_data["Weights"]
                ):
                    logging.info(f"    {asset}: {weight:.4f}")

                # Calculate and log comprehensive metrics for Second Best Target Vol portfolio
                second_best_comprehensive = calculate_comprehensive_portfolio_metrics(
                    second_best_target_vol_portfolio_data["Weights"],
                    returns_df,
                    risk_free_rate,
                    periods_per_year,
                )
                log_comprehensive_metrics(
                    second_best_comprehensive,
                    f"Second Best Target Vol Portfolio (EF near {target_volatility:.2%})",
                )

            if len(selected_distinct_ef_portfolios) > 2:
                third_best_target_vol_portfolio_data = selected_distinct_ef_portfolios[
                    2
                ]
                logging.info(
                    f"\nThird Best Target Volatility Portfolio (from Efficient Frontier near {target_volatility:.4f}):"
                )
                logging.info(
                    f"  Return: {third_best_target_vol_portfolio_data['Return']:.4f}"
                )
                logging.info(
                    f"  Volatility: {third_best_target_vol_portfolio_data['Volatility']:.4f}"
                )
                logging.info(
                    f"  Sharpe Ratio: {third_best_target_vol_portfolio_data['Sharpe Ratio']:.4f}"
                )
                logging.info("  Weights:")
                for asset, weight in zip(
                    returns_df.columns, third_best_target_vol_portfolio_data["Weights"]
                ):
                    logging.info(f"    {asset}: {weight:.4f}")

                # Calculate and log comprehensive metrics for Third Best Target Vol portfolio
                third_best_comprehensive = calculate_comprehensive_portfolio_metrics(
                    third_best_target_vol_portfolio_data["Weights"],
                    returns_df,
                    risk_free_rate,
                    periods_per_year,
                )
                log_comprehensive_metrics(
                    third_best_comprehensive,
                    f"Third Best Target Vol Portfolio (EF near {target_volatility:.2%})",
                )
        else:
            logging.error(
                f"Optimization for target volatility {target_volatility:.4f} failed: {opt_target_vol.message}. This might mean the target volatility is unachievable given the assets and constraints."
            )

    # --- Plotting the efficient frontier with optimized portfolios ---
    plt.figure(figsize=(12, 8))
    plt.scatter(
        portfolio_results_df["Volatility"],
        portfolio_results_df["Return"],
        c=portfolio_results_df["Sharpe_Ratio"],
        cmap="viridis",
        marker="o",
        s=10,
        alpha=0.6,
        label="Random Portfolios (Monte Carlo)",
    )
    plt.colorbar(label="Sharpe Ratio")

    # Plot the analytical efficient frontier
    plt.plot(
        efficient_frontier_volatilities,
        efficient_frontier_returns,
        color="darkgreen",
        linestyle="-",
        linewidth=2,
        label="Efficient Frontier",
    )

    plt.title("Portfolio Optimization: Efficient Frontier")
    plt.xlabel("Annualized Volatility (Standard Deviation)")
    plt.ylabel("Annualized Return")
    plt.grid(True, linestyle="--", alpha=0.7)

    # Highlight Max Sharpe Ratio portfolio from scipy.optimize
    plt.scatter(
        max_sharpe_volatility,
        max_sharpe_return,
        marker="*",
        color="red",
        s=500,
        label="Maximum Sharpe Ratio Portfolio (Optimized)",
    )

    # Highlight Minimum Volatility portfolio from scipy.optimize
    plt.scatter(
        min_vol_volatility,
        min_vol_return,
        marker="*",
        color="blue",
        s=500,
        label="Minimum Volatility Portfolio (Optimized)",
    )

    # Highlight Target Volatility portfolio (if found) - this is the "best" one
    if target_vol_portfolio_data:
        plt.scatter(
            target_vol_portfolio_data["Volatility"],
            target_vol_portfolio_data["Return"],
            marker="X",
            color="purple",
            s=500,
            label=f"Target Volatility ({target_vol_portfolio_data['Volatility']:.2f}) Portfolio (Optimized Best)",
        )

    # Highlight 2nd and 3rd Best Target Volatility portfolios from Efficient Frontier (if found)
    # These are points *on* the efficient frontier that are closest to the target volatility
    if second_best_target_vol_portfolio_data:
        plt.scatter(
            second_best_target_vol_portfolio_data["Volatility"],
            second_best_target_vol_portfolio_data["Return"],
            marker="o",
            color="gold",
            s=300,
            edgecolors="black",
            linewidth=1,
            label=f"Target Volatility ({second_best_target_vol_portfolio_data['Volatility']:.2f}) Portfolio (EF Close 1st)",
        )

