def parse_portfolio_exploration_log(log_path):
    """
    Parse a portfolio exploration log file to extract user-defined portfolios.

    Extracts portfolio data (weights, return, volatility, sharpe) from log files
    generated by portfolio_exploration_global.py.

    Parameters:
    -----------
    log_path : str
        Path to the portfolio exploration log file

    Returns:
    --------
    dict
        Dictionary with portfolio types as keys, containing:
        - 'weights': dict of {ticker: weight}
        - 'return': annualized return
        - 'volatility': annualized volatility
        - 'sharpe': Sharpe ratio
        - 'name': portfolio type name

    Example output:
    {
        'max_sharpe': {'weights': {'NVDA': 0.07, 'SPY': 0.05, ...}, 'return': 0.57, 'volatility': 0.14, 'sharpe': 3.43},
        'min_volatility': {...},
        'hrp': {...}
    }
    """
    import re

    if not os.path.exists(log_path):
        logging.warning(f"Portfolio log file not found: {log_path}")
        return {}

    with open(log_path, "r") as f:
        content = f.read()

    portfolios = {}

    # Find the COMPLETE PORTFOLIO HOLDINGS section
    holdings_match = re.search(
        r"COMPLETE PORTFOLIO HOLDINGS.*?(?=ASSET OVERLAP|DECISION INSIGHTS|$)",
        content,
        re.DOTALL,
    )
    if not holdings_match:
        logging.warning("Could not find COMPLETE PORTFOLIO HOLDINGS section in log")
        return {}

    holdings_section = holdings_match.group(0)

    # Parse each portfolio type
    portfolio_patterns = [
        (
            "max_sharpe",
            r"MAX SHARPE:\s*\n\s*Return:\s*([\d.]+)\s*\n\s*Volatility:\s*([\d.]+)\s*\n\s*Sharpe:\s*([\d.]+)",
        ),
        (
            "min_volatility",
            r"MIN VOLATILITY:\s*\n\s*Return:\s*([\d.]+)\s*\n\s*Volatility:\s*([\d.]+)\s*\n\s*Sharpe:\s*([\d.]+)",
        ),
        (
            "hrp",
            r"HRP:\s*\n\s*Return:\s*([\d.]+)\s*\n\s*Volatility:\s*([\d.]+)\s*\n\s*Sharpe:\s*([\d.]+)",
        ),
    ]

    for port_name, pattern in portfolio_patterns:
        match = re.search(pattern, holdings_section)
        if match:
            ret, vol, sharpe = (
                float(match.group(1)),
                float(match.group(2)),
                float(match.group(3)),
            )

            # Find weights for this portfolio
            # Look for "All Holdings:" section after this match
            port_section_start = match.end()

            # Find the start of next portfolio or end of section
            next_port = None
            for other_name, _ in portfolio_patterns:
                if other_name != port_name:
                    next_match = re.search(
                        rf"{other_name.upper().replace('_', ' ')}:",
                        holdings_section[port_section_start:],
                    )
                    if next_match and (
                        next_port is None or next_match.start() < next_port
                    ):
                        next_port = next_match.start()

            if next_port:
                port_section = holdings_section[
                    port_section_start : port_section_start + next_port
                ]
            else:
                port_section = holdings_section[port_section_start:]

            # Parse weights: "1. TICKER                             0.0700 (  7.00%)"
            weights = {}
            weight_pattern = r"\d+\.\s+(\S+)\s+([\d.]+)\s+\("
            for w_match in re.finditer(weight_pattern, port_section):
                ticker = w_match.group(1)
                weight = float(w_match.group(2))
                weights[ticker] = weight

            if weights:
                portfolios[port_name] = {
                    "weights": weights,
                    "return": ret,
                    "volatility": vol,
                    "sharpe": sharpe,
                    "name": port_name.replace("_", " ").title(),
                }
                logging.info(
                    f"  Parsed {port_name}: Return={ret:.4f}, Vol={vol:.4f}, Sharpe={sharpe:.4f}, {len(weights)} assets"
                )

    if portfolios:
        logging.info(
            f"Successfully parsed {len(portfolios)} portfolios from {log_path}"
        )
    else:
        logging.warning(f"No portfolios found in {log_path}")

    return portfolios


def load_and_preprocess_data(file_path, start_date=None, end_date=None, seed=42):
    """
    Loads financial data from a CSV, preprocesses it, and calculates logarithmic returns.
    Applies date filtering if start_date and end_date are provided.
    If the file is not found, it generates synthetic data for demonstration.

    Parameters:
    -----------
    file_path : str
        The path to the CSV file containing financial data.
    start_date : str, optional
        Start date for filtering data (YYYY-MM-DD). If None, no start date filter applied.
    end_date : str, optional
        End date for filtering data (YYYY-MM-DD). If None, no end date filter applied.
    seed : int, optional
        Random seed for synthetic data generation fallback (default: 42).
    Returns:
    --------
    pd.DataFrame
        A DataFrame containing the logarithmic returns for each asset.
    """
    try:
        # Load the data -- support both CSV and parquet formats
        if str(file_path).endswith(".parquet"):
            df = pd.read_parquet(file_path)
            if df.index.name != "Date":
                df.index.name = "Date"
        else:
            df = pd.read_csv(file_path, index_col="Date", parse_dates=True)
        logging.info(f"Successfully loaded data from '{file_path}'.")
    except FileNotFoundError:
        logging.warning(
            f"Warning: The file '{file_path}' was not found. Generating synthetic data for demonstration."
        )
        # Generate synthetic data
        start = (
            datetime.strptime(start_date, "%Y-%m-%d")
            if start_date
            else datetime(2024, 1, 1)
        )
        end = (
            datetime.strptime(end_date, "%Y-%m-%d")
            if end_date
            else datetime(2025, 6, 1)
        )

        dates = pd.date_range(start=start, end=end, freq="B")  # Business days
        num_assets = 9  # Match the original 9 assets
        asset_names = [
            "SPY",
            "GLD",
            "NVDA",
            "TSLA",
            "QQQ",
            "EURUSD",
            "GBPUSD",
            "NFLX",
            "USDJPY",
        ]

        # Simulate price data - start at 100 and add random daily changes
        # Ensure positive prices with np.exp of cumulative returns
        np.random.seed(seed)  # for reproducibility
        daily_returns_synthetic = np.random.normal(
            0.0005, 0.01, size=(len(dates), num_assets)
        )  # Mean 0.05%, Std 1%

        # Convert daily returns to price series
        prices = pd.DataFrame(
            np.exp(np.cumsum(daily_returns_synthetic, axis=0)),
            index=dates,
            columns=asset_names,
        )
        prices = prices * 100  # Scale prices to a reasonable level

        df = prices
        logging.info("Synthetic data generated successfully.")

    except Exception as e:
        logging.error(
            f"An unexpected error occurred during data loading: {e}", exc_info=True
        )
        return pd.DataFrame()  # Return empty DataFrame to signal failure

    logging.info(f"Original data shape: {df.shape}")

    # Drop rows where all values are NaN (e.g., empty rows or header-only rows)
    df = df.dropna(how="all")

    # Apply date filtering if specified
    if start_date:
        df = df.loc[df.index >= start_date]
        logging.info(
            f"Filtered data from start date {start_date}. New shape: {df.shape}"
        )
    if end_date:
        df = df.loc[df.index <= end_date]
        logging.info(f"Filtered data to end date {end_date}. New shape: {df.shape}")
    # Drop tickers with insufficient data coverage in the requested timeframe.
    # Tickers that IPO'd after the start date (or were delisted before end date)
    # would be mostly NaN, causing log returns to collapse to (0, N) after dropna.
    # NOTE: When mixing tickers from multiple exchanges (US, JP, EU, ME), the
    # date index is the UNION of all trading calendars. A US-only ticker has NaN
    # on Japan-only trading days and vice versa.  Middle-Eastern exchanges (e.g.
    # DFM .AE, Tadawul .SR) trade Sun-Thu, so they are systematically NaN on
    # Fridays and may lack Sunday rows depending on the data source.
    #
    # To avoid penalising tickers whose exchange calendar differs from Mon-Fri,
    # we compute coverage **per ticker** using each ticker's own observed trading
    # weekdays as the denominator: for each column we determine which weekdays
    # it has ever had data on, count how many index dates fall on those weekdays,
    # and use that as the ticker-specific expected trading day count.
    total_rows = len(df)
    if total_rows > 0:
        non_nan_mask = df.notna()
        non_nan_counts = non_nan_mask.sum()

        # Per-ticker calendar-aware denominator.  For each ticker we identify
        # its regular trading weekdays (Mon=0 … Sun=6) and count only index
        # dates on those weekdays as "expected" trading days.  To avoid stray
        # data points (e.g. a single Friday print for a Sun-Thu exchange)
        # inflating the denominator, a weekday is only counted as a regular
        # trading day if the ticker has data on > 10% of that weekday's
        # occurrences in the index.
        idx_weekdays = df.index.dayofweek  # 0=Mon … 6=Sun
        # Pre-compute weekday counts in the full index
        wday_total_counts = idx_weekdays.value_counts()

        coverage = pd.Series(index=df.columns, dtype=float)
        for col in df.columns:
            col_nonnull_wdays = idx_weekdays[non_nan_mask[col]]
            col_wday_counts = col_nonnull_wdays.value_counts()
            # Keep weekdays where ticker has data on >10% of that weekday
            trading_wdays = set()
            for wd, cnt in col_wday_counts.items():
                if cnt / wday_total_counts.get(wd, 1) > 0.10:
                    trading_wdays.add(wd)
            # Expected trading days = index dates falling on regular weekdays
            expected = (idx_weekdays.isin(trading_wdays)).sum()
            coverage[col] = non_nan_counts[col] / max(expected, 1)

        # Require at least 80% coverage relative to per-ticker trading days
        min_coverage = 0.8
        bad_cols = coverage[coverage < min_coverage].index.tolist()
        if bad_cols:
            logging.info(
                f"Excluding {len(bad_cols)} tickers with < {min_coverage:.0%} data coverage "
                f"in requested timeframe (e.g., IPO after start date). "
                f"{len(df.columns) - len(bad_cols)} tickers retained."
            )
            logging.info(
                f"  Excluded tickers: {bad_cols[:20]}{'...' if len(bad_cols) > 20 else ''}"
            )
            df = df.drop(columns=bad_cols)
        else:
            logging.info(
                f"All {len(df.columns)} tickers have >= {min_coverage:.0%} data coverage. None excluded."
            )

    # Forward-fill and then backward-fill to handle remaining minor gaps
    df = df.ffill().bfill()
    if df.empty:
        logging.error(
            "DataFrame is empty after loading and cleaning or filtering. Check input data and date range."
        )
        return pd.DataFrame()
    # Calculate logarithmic returns
    log_returns = np.log(df / df.shift(1)).dropna()
    logging.info(f"Logarithmic returns calculated. Shape: {log_returns.shape}")
    if log_returns.empty:
        logging.error(
            "Log returns DataFrame is empty after calculation. Check data frequency and completeness."
        )
        return pd.DataFrame()
    return log_returns


def perform_normality_tests(returns_df, output_dir, timestamp):
    """
    Performs normality tests and generates Q-Q plots for each series in the DataFrame.

    Parameters:
    -----------
    returns_df : pd.DataFrame
        DataFrame of logarithmic returns, where each column represents an asset.
    output_dir : str
        Directory to save the Q-Q plots.
    timestamp : str
        Unique timestamp for filenames.
    """
    if returns_df.empty:
        logging.warning("No data available to perform normality tests.")
        return

    logging.info(
        f"\n--- Performing Normality Tests on {len(returns_df.columns)} Assets ---"
    )

    # Determine optimal subplot grid for Q-Q plots
    num_assets = returns_df.shape[1]
    cols = min(4, num_assets)  # Max 4 columns for plots
    rows = (num_assets + cols - 1) // cols  # Calculate rows needed

    fig, axes = plt.subplots(rows, cols, figsize=(cols * 5, rows * 4), squeeze=False)
    axes = axes.flatten()  # Flatten the 2D array of axes for easy iteration

    for i, column in enumerate(returns_df.columns):
        data = returns_df[column].dropna()
        if data.empty:
            logging.warning(
                f"Skipping '{column}' due to no valid data for normality test."
            )
            continue

        logging.info(f"\nResults for '{column}':")
        # Skewness Test
        skew, p_value_skew = scs.skewtest(data)
        logging.info(f"  Skew of data set: {scs.skew(data):>14.4f}")
        logging.info(
            f"  Skew test p-value: {p_value_skew:>13.4f} ({'Normal' if p_value_skew > 0.05 else 'Not Normal'} at 5% level)"
        )

        # Kurtosis Test
        kurt, p_value_kurt = scs.kurtosistest(data)
        logging.info(f"  Kurtosis of data set: {scs.kurtosis(data):>12.4f}")
        logging.info(
            f"  Kurtosis test p-value: {p_value_kurt:>9.4f} ({'Normal' if p_value_kurt > 0.05 else 'Not Normal'} at 5% level)"
        )

        # Jarque-Bera Test (Omnibus Test)
        _, p_value_jb = scs.jarque_bera(data)
        logging.info(
            f"  Jarque-Bera test p-value: {p_value_jb:>7.4f} ({'Normal' if p_value_jb > 0.05 else 'Not Normal'} at 5% level)"
        )

        # Generate Q-Q plot
        ax = axes[i]
        sm.qqplot(data, line="s", ax=ax)
        ax.set_title(f"Q-Q Plot for {column}", fontsize=10)
        ax.tick_params(axis="both", which="major", labelsize=8)
        ax.set_xlabel("Theoretical Quantiles", fontsize=8)
        ax.set_ylabel("Sample Quantiles", fontsize=8)

    # Hide unused subplots
    for j in range(i + 1, len(axes)):
        fig.delaxes(axes[j])
    plt.tight_layout()
    plot_path = os.path.join(output_dir, f"qq_plots_all_assets_{timestamp}.png")
    plt.savefig(plot_path, dpi=300)
    plt.close(fig)  # Close the figure to free memory
    logging.info(f"\nQ-Q plots saved to '{plot_path}'")


# --- Portfolio Optimization Functions (for scipy.optimize) ---
def statistics(weights, mean_returns, cov_matrix, risk_free_rate, periods_per_year=252):
    """
    Calculates portfolio return, volatility, and Sharpe ratio.
    Used as a helper for optimization functions.

    Parameters:
    -----------
    periods_per_year : int
        Annualization factor (252 for daily, 52 for weekly, 12 for monthly)
    """
    portfolio_return = np.sum(mean_returns * weights) * periods_per_year
    portfolio_volatility = np.sqrt(
        np.dot(weights.T, np.dot(cov_matrix, weights))
    ) * np.sqrt(periods_per_year)
    sharpe_ratio = (portfolio_return - risk_free_rate) / portfolio_volatility
    return np.array([portfolio_return, portfolio_volatility, sharpe_ratio])


def min_func_sharpe(
    weights, mean_returns, cov_matrix, risk_free_rate, periods_per_year=252
):
    """
    Objective function to minimize the negative Sharpe ratio.
    """
    return -statistics(
        weights, mean_returns, cov_matrix, risk_free_rate, periods_per_year
    )[2]


def min_func_volatility(weights, mean_returns, cov_matrix, periods_per_year=252):
    """
    Objective function to minimize the portfolio volatility.
    """
    return statistics(weights, mean_returns, cov_matrix, 0.0, periods_per_year)[
        1
    ]  # Risk-free rate is irrelevant for min volatility


def max_func_return(
    weights, mean_returns, cov_matrix, risk_free_rate, periods_per_year=252
):
    """
    Objective function to maximize portfolio return (by minimizing negative return).
    """
    return -statistics(
        weights, mean_returns, cov_matrix, risk_free_rate, periods_per_year
    )[0]


